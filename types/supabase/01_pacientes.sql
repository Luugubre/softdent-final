CREATE TABLE IF NOT EXISTS public.pacientes (
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  numero_ficha         bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,

  -- Identificación
  rut                  text NOT NULL UNIQUE,         -- "12345678-9" o documento si es extranjero
  extranjero           boolean NOT NULL DEFAULT false,
  nombres              text NOT NULL,
  apellidos            text NOT NULL,
  nombre_social        text,
  fecha_nacimiento     date NOT NULL,
  sexo                 text,
  genero               text,

  -- Contacto
  telefono             text,
  telefono_fijo        text,
  email                text,
  direccion            text,
  comuna               text,
  ciudad               text,

  -- Datos complementarios
  prevision            text NOT NULL DEFAULT 'Particular',
  actividad_profesion  text,
  empleador            text,
  referencia           text,                          -- ¿cómo nos conoció?
  observaciones        text,

  -- Apoderado (obligatorio para menores de 18)
  apoderado_nombre     text,
  apoderado_rut        text,
  apoderado_telefono   text,

  -- Carga familiar
  titular_id           uuid REFERENCES public.pacientes(id) ON DELETE SET NULL,

  -- Estado
  activo               boolean NOT NULL DEFAULT true,
  motivo_deshabilitado text,

  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),

  -- Reglas de integridad
  CONSTRAINT pacientes_rut_formato_chk
    CHECK (extranjero OR rut ~ '^[0-9]{7,8}-[0-9K]$'),
  CONSTRAINT pacientes_sexo_chk
    CHECK (sexo IS NULL OR sexo IN ('FEMENINO', 'MASCULINO', 'INTERSEXUAL', 'NO_INFORMA')),
  CONSTRAINT pacientes_fecha_nacimiento_chk
    CHECK (fecha_nacimiento <= CURRENT_DATE AND fecha_nacimiento >= DATE '1900-01-01'),
  CONSTRAINT pacientes_email_chk
    CHECK (email IS NULL OR email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  CONSTRAINT pacientes_titular_distinto_chk
    CHECK (titular_id IS NULL OR titular_id <> id)
);

-- Índices para el buscador
CREATE INDEX IF NOT EXISTS pacientes_apellidos_idx ON public.pacientes (lower(apellidos));
CREATE INDEX IF NOT EXISTS pacientes_nombres_idx   ON public.pacientes (lower(nombres));
CREATE INDEX IF NOT EXISTS pacientes_titular_idx   ON public.pacientes (titular_id);

-- updated_at automático
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS pacientes_set_updated_at ON public.pacientes;
CREATE TRIGGER pacientes_set_updated_at
  BEFORE UPDATE ON public.pacientes
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Seguridad: RLS activado y sin políticas = nadie puede leer la tabla desde
-- el navegador con la anon key. La app accede solo desde el servidor con la
-- service role key. Cuando esté el login (módulo de Rodrigo) se agregan políticas por rol.
ALTER TABLE public.pacientes ENABLE ROW LEVEL SECURITY;
