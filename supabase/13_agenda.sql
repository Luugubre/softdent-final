-- Tablas antiguas del SQL de Prisma (id de tipo text) → se eliminan
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['citas', 'bloqueos_agenda', 'horarios_atencion', 'boxes'] LOOP
    IF EXISTS (SELECT 1 FROM information_schema.columns
                WHERE table_schema = 'public' AND table_name = t AND column_name = 'id' AND data_type = 'text') THEN
      EXECUTE format('DROP TABLE public.%I CASCADE', t);
    END IF;
  END LOOP;
END;
$$;

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- Fecha y hora de Chile → timestamptz
CREATE OR REPLACE FUNCTION public.hora_chile(p_fecha date, p_hora time)
RETURNS timestamptz LANGUAGE sql STABLE AS $$
  SELECT (p_fecha + p_hora) AT TIME ZONE 'America/Santiago';
$$;


-- =====================================================================
-- 1. BOXES
