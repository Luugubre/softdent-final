CREATE TABLE IF NOT EXISTS public.boxes (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre     text NOT NULL UNIQUE CHECK (length(trim(nombre)) > 0),
  activo     boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.boxes ENABLE ROW LEVEL SECURITY;

INSERT INTO public.boxes (nombre) VALUES ('Box 1'), ('Box 2') ON CONFLICT (nombre) DO NOTHING;


-- =====================================================================
-- 2. HORARIOS DE ATENCIÓN (por profesional y día de la semana)
-- dia_semana: 1 = lunes ... 7 = domingo
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.horarios_atencion (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  profesional_id uuid NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  dia_semana     integer NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
  hora_inicio    time NOT NULL,
  hora_fin       time NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT horarios_rango_chk CHECK (hora_fin > hora_inicio),
  -- Regla: los horarios de un profesional no se solapan
  CONSTRAINT horarios_sin_solapamiento EXCLUDE USING gist (
    profesional_id WITH =,
    dia_semana WITH =,
    tsrange('2000-01-01'::date + hora_inicio, '2000-01-01'::date + hora_fin) WITH &&
  )
);
ALTER TABLE public.horarios_atencion ENABLE ROW LEVEL SECURITY;


-- =====================================================================
-- 3. BLOQUEOS (vacaciones, reuniones, mantención...)
-- Sin profesional ni box = bloqueo de toda la clínica
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.bloqueos_agenda (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tipo           text NOT NULL DEFAULT 'OTRO',
  motivo         text NOT NULL CHECK (length(trim(motivo)) > 0),
  inicio         timestamptz NOT NULL,
  fin            timestamptz NOT NULL,
  profesional_id uuid REFERENCES public.perfiles(id) ON DELETE CASCADE,
  box_id         uuid REFERENCES public.boxes(id) ON DELETE CASCADE,
  creado_por     uuid REFERENCES public.perfiles(id) ON DELETE SET NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT bloqueos_tipo_chk CHECK (tipo IN ('VACACIONES', 'REUNION', 'MANTENCION', 'OTRO')),
  CONSTRAINT bloqueos_rango_chk CHECK (fin > inicio)
);
CREATE INDEX IF NOT EXISTS bloqueos_rango_idx ON public.bloqueos_agenda USING gist (tstzrange(inicio, fin));
ALTER TABLE public.bloqueos_agenda ENABLE ROW LEVEL SECURITY;


-- =====================================================================
-- 4. CITAS
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.citas (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  numero             bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  paciente_id        uuid NOT NULL REFERENCES public.pacientes(id) ON DELETE RESTRICT,
  profesional_id     uuid NOT NULL REFERENCES public.perfiles(id) ON DELETE RESTRICT,
  box_id             uuid REFERENCES public.boxes(id) ON DELETE RESTRICT,
  prestacion_id      uuid REFERENCES public.prestaciones(id) ON DELETE RESTRICT,
  inicio             timestamptz NOT NULL,
  fin                timestamptz NOT NULL,
  duracion_min       integer NOT NULL,
  estado             text NOT NULL DEFAULT 'AGENDADA',
  motivo             text,                       -- motivo de consulta / notas
  sobrecupo          boolean NOT NULL DEFAULT false,
  motivo_sobrecupo   text,
  motivo_cancelacion text,
  cita_original_id   uuid UNIQUE REFERENCES public.citas(id) ON DELETE RESTRICT,  -- si viene de un reagendamiento
  creado_por         uuid REFERENCES public.perfiles(id) ON DELETE SET NULL,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT citas_estado_chk CHECK (estado IN
    ('AGENDADA', 'CONFIRMADA', 'EN_ATENCION', 'REALIZADA', 'CANCELADA', 'NO_ASISTIO', 'REAGENDADA')),
  CONSTRAINT citas_duracion_chk CHECK (duracion_min BETWEEN 5 AND 480 AND fin = inicio + make_interval(mins => duracion_min)),
  CONSTRAINT citas_sobrecupo_chk CHECK (NOT sobrecupo OR length(trim(COALESCE(motivo_sobrecupo, ''))) > 0),
  CONSTRAINT citas_cancelacion_chk CHECK (estado <> 'CANCELADA' OR length(trim(COALESCE(motivo_cancelacion, ''))) > 0),

  -- Regla de oro: sin doble reserva (solo cuentan las citas vigentes)
  CONSTRAINT citas_sin_choque_profesional EXCLUDE USING gist (
    profesional_id WITH =, tstzrange(inicio, fin) WITH &&
  ) WHERE (estado IN ('AGENDADA', 'CONFIRMADA', 'EN_ATENCION') AND NOT sobrecupo),
  CONSTRAINT citas_sin_choque_box EXCLUDE USING gist (
    box_id WITH =, tstzrange(inicio, fin) WITH &&
  ) WHERE (estado IN ('AGENDADA', 'CONFIRMADA', 'EN_ATENCION') AND NOT sobrecupo AND box_id IS NOT NULL),
  CONSTRAINT citas_sin_choque_paciente EXCLUDE USING gist (
    paciente_id WITH =, tstzrange(inicio, fin) WITH &&
  ) WHERE (estado IN ('AGENDADA', 'CONFIRMADA', 'EN_ATENCION'))
);

CREATE INDEX IF NOT EXISTS citas_inicio_idx ON public.citas (inicio);
CREATE INDEX IF NOT EXISTS citas_paciente_idx ON public.citas (paciente_id, inicio DESC);
ALTER TABLE public.citas ENABLE ROW LEVEL SECURITY;

