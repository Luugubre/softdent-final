CREATE TRIGGER bonos_no_borrar BEFORE DELETE ON public.bonos_fonasa
  FOR EACH ROW EXECUTE FUNCTION public.catalogo_no_borrar();

CREATE OR REPLACE FUNCTION public.registrar_bono(
  p_folio      text,
  p_paciente   uuid,
  p_prestacion uuid,
  p_monto      integer,
  p_usuario    uuid,
  p_copago     integer DEFAULT 0,
  p_item       uuid DEFAULT NULL,
  p_fecha      date DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE
  v_id uuid;
  v_folio text := upper(trim(COALESCE(p_folio, '')));
  v_codigo text;
  v_item public.presupuesto_items%ROWTYPE;
BEGIN
  IF length(v_folio) = 0 THEN RAISE EXCEPTION 'Ingresa el N° de folio del bono.'; END IF;
  IF EXISTS (SELECT 1 FROM public.bonos_fonasa WHERE folio = v_folio) THEN
    RAISE EXCEPTION '%', 'El folio ' || v_folio || ' ya está registrado: un folio no se reutiliza.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.pacientes WHERE id = p_paciente) THEN RAISE EXCEPTION 'Paciente no encontrado.'; END IF;
  SELECT codigo_fonasa INTO v_codigo FROM public.prestaciones WHERE id = p_prestacion AND activo;
  IF NOT FOUND THEN RAISE EXCEPTION 'La prestación no existe o está desactivada.'; END IF;
  IF v_codigo IS NULL OR length(trim(v_codigo)) = 0 THEN
    RAISE EXCEPTION 'La prestación no tiene código FONASA: no puede bonificarse.';
  END IF;
  IF p_monto IS NULL OR p_monto <= 0 THEN RAISE EXCEPTION 'El monto bonificado debe ser mayor a cero.'; END IF;
  IF COALESCE(p_copago, 0) < 0 THEN RAISE EXCEPTION 'El copago no puede ser negativo.'; END IF;
  IF p_fecha IS NOT NULL AND p_fecha > public.hoy_chile() THEN RAISE EXCEPTION 'La fecha de emisión no puede ser futura.'; END IF;
  IF p_item IS NOT NULL THEN
    SELECT * INTO v_item FROM public.presupuesto_items WHERE id = p_item;
    IF NOT FOUND OR v_item.paciente_id <> p_paciente OR v_item.estado = 'ANULADO' THEN
      RAISE EXCEPTION 'La prestación del plan no pertenece al paciente o está anulada.';
    END IF;
    IF v_item.prestacion_id <> p_prestacion THEN RAISE EXCEPTION 'El bono es de otra prestación que la del plan seleccionada.'; END IF;
  END IF;

  INSERT INTO public.bonos_fonasa (folio, paciente_id, prestacion_id, item_id, monto_bonificado, copago, fecha_emision, creado_por)
  VALUES (v_folio, p_paciente, p_prestacion, p_item, p_monto, COALESCE(p_copago, 0), COALESCE(p_fecha, public.hoy_chile()), p_usuario)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

-- Usar el bono: si cubre una prestación del plan, se registra como pago (método BONO_FONASA)
CREATE OR REPLACE FUNCTION public.usar_bono(p_bono uuid, p_usuario uuid, p_item uuid DEFAULT NULL)
RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE
  b public.bonos_fonasa%ROWTYPE;
  v_item uuid;
  v_saldo integer;
  v_monto integer;
  v_pago uuid;
BEGIN
  SELECT * INTO b FROM public.bonos_fonasa WHERE id = p_bono FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Bono no encontrado.'; END IF;
  IF b.estado <> 'PENDIENTE' THEN RAISE EXCEPTION '%', 'El bono está ' || lower(b.estado) || ': no se puede volver a usar.'; END IF;
  v_item := COALESCE(p_item, b.item_id);

  IF v_item IS NOT NULL THEN
    SELECT precio - abonado INTO v_saldo FROM public.presupuesto_items
     WHERE id = v_item AND paciente_id = b.paciente_id AND prestacion_id = b.prestacion_id AND estado <> 'ANULADO';
    IF NOT FOUND THEN RAISE EXCEPTION 'La prestación del plan no corresponde a este bono.'; END IF;
    v_monto := LEAST(b.monto_bonificado, v_saldo);
    IF v_monto > 0 THEN
      v_pago := public.registrar_pago(b.paciente_id, v_monto, 'BONO_FONASA',
                  jsonb_build_array(jsonb_build_object('item_id', v_item, 'monto', v_monto)),
                  p_usuario, b.folio, NULL, 'Bono FONASA folio ' || b.folio);
    END IF;
  END IF;

  UPDATE public.bonos_fonasa SET estado = 'UTILIZADO', usado_en = now(), item_id = v_item, pago_id = v_pago WHERE id = p_bono;
  RETURN v_pago;
END;
$$;

CREATE OR REPLACE FUNCTION public.anular_bono(p_bono uuid, p_usuario uuid, p_motivo text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_estado text;
BEGIN
  IF length(trim(COALESCE(p_motivo, ''))) < 3 THEN RAISE EXCEPTION 'Indica el motivo de la anulación del bono.'; END IF;
  SELECT estado INTO v_estado FROM public.bonos_fonasa WHERE id = p_bono FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Bono no encontrado.'; END IF;
  IF v_estado = 'UTILIZADO' THEN RAISE EXCEPTION 'Un bono utilizado no puede anularse (anula el pago que generó, si corresponde).'; END IF;
  IF v_estado = 'ANULADO' THEN RAISE EXCEPTION 'El bono ya está anulado.'; END IF;
  UPDATE public.bonos_fonasa SET estado = 'ANULADO', motivo_anulacion = trim(p_motivo), anulado_en = now() WHERE id = p_bono;
END;
$$;


