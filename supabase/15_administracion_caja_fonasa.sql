-- Las funciones de este script guardan el usuario en "app.usuario" para que el trigger lo registre
CREATE OR REPLACE FUNCTION public.usuario_actual_app()
RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT NULLIF(current_setting('app.usuario', true), '')::uuid;
$$;

CREATE OR REPLACE FUNCTION public.auditar_cambios()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v_id text := COALESCE(to_jsonb(NEW) ->> 'id', to_jsonb(NEW) ->> 'codigo', to_jsonb(NEW) ->> 'clave');
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.auditoria (tabla, registro_id, accion, nuevo, usuario_id)
    VALUES (TG_TABLE_NAME, v_id, 'CREADO', to_jsonb(NEW), public.usuario_actual_app());
  ELSIF to_jsonb(NEW) - 'updated_at' IS DISTINCT FROM to_jsonb(OLD) - 'updated_at' THEN
    INSERT INTO public.auditoria (tabla, registro_id, accion, anterior, nuevo, usuario_id)
    VALUES (TG_TABLE_NAME, v_id, 'MODIFICADO', to_jsonb(OLD), to_jsonb(NEW), public.usuario_actual_app());
  END IF;
  RETURN NEW;
END;
$$;

