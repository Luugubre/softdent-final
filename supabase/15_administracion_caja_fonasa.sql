-- Reglas: sin caja abierta no hay movimientos; caja cerrada no se toca; nada se borra
CREATE OR REPLACE FUNCTION public.caja_movimientos_proteger()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_estado text;
BEGIN
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'Los movimientos de caja no se eliminan: se anulan.'; END IF;
  SELECT estado INTO v_estado FROM public.cajas WHERE id = NEW.caja_id;
  IF v_estado <> 'ABIERTA' THEN
    RAISE EXCEPTION 'La caja está cerrada: las correcciones se hacen con un movimiento de ajuste en la caja abierta.';
  END IF;
  IF TG_OP = 'UPDATE' THEN
    IF OLD.anulado OR NOT NEW.anulado
       OR (NEW.monto, NEW.tipo, NEW.metodo, NEW.caja_id) IS DISTINCT FROM (OLD.monto, OLD.tipo, OLD.metodo, OLD.caja_id) THEN
      RAISE EXCEPTION 'Un movimiento de caja no se modifica: solo se anula.';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS caja_movimientos_proteger_trg ON public.caja_movimientos;
CREATE TRIGGER caja_movimientos_proteger_trg BEFORE INSERT OR UPDATE OR DELETE ON public.caja_movimientos
  FOR EACH ROW EXECUTE FUNCTION public.caja_movimientos_proteger();

CREATE OR REPLACE FUNCTION public.cajas_proteger()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'Las cajas no se eliminan.'; END IF;
  IF OLD.estado = 'CERRADA' THEN RAISE EXCEPTION 'Una caja cerrada no admite modificaciones.'; END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS cajas_proteger_trg ON public.cajas;
CREATE TRIGGER cajas_proteger_trg BEFORE UPDATE OR DELETE ON public.cajas
  FOR EACH ROW EXECUTE FUNCTION public.cajas_proteger();

CREATE OR REPLACE FUNCTION public.caja_abierta()
RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT id FROM public.cajas WHERE estado = 'ABIERTA' LIMIT 1;
$$;

-- Efectivo que debería haber en la gaveta
CREATE OR REPLACE FUNCTION public.efectivo_esperado(p_caja uuid)
RETURNS integer LANGUAGE sql STABLE AS $$
  SELECT c.monto_inicial + COALESCE((
    SELECT sum(CASE WHEN m.tipo = 'INGRESO' THEN m.monto ELSE -m.monto END)
      FROM public.caja_movimientos m JOIN public.metodos_pago mp ON mp.codigo = m.metodo
     WHERE m.caja_id = c.id AND NOT m.anulado AND mp.es_efectivo), 0)::int
  FROM public.cajas c WHERE c.id = p_caja;
$$;

CREATE OR REPLACE FUNCTION public.abrir_caja(p_monto integer, p_usuario uuid, p_nota text DEFAULT NULL)
RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE v_id uuid;
BEGIN
  IF p_monto IS NULL OR p_monto < 0 THEN RAISE EXCEPTION 'El monto inicial debe ser 0 o mayor.'; END IF;
  IF public.caja_abierta() IS NOT NULL THEN RAISE EXCEPTION 'Ya hay una caja abierta: ciérrala antes de abrir otra.'; END IF;
  INSERT INTO public.cajas (monto_inicial, abierta_por, nota_apertura) VALUES (p_monto, p_usuario, NULLIF(trim(p_nota), ''))
  RETURNING id INTO v_id;
  RETURN v_id;
EXCEPTION WHEN unique_violation THEN
  RAISE EXCEPTION 'Ya hay una caja abierta: ciérrala antes de abrir otra.';
END;
$$;

CREATE OR REPLACE FUNCTION public.registrar_movimiento_caja(
  p_tipo text, p_monto integer, p_metodo text, p_descripcion text, p_usuario uuid, p_origen text DEFAULT 'MANUAL'
) RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE
  v_caja uuid := public.caja_abierta();
  v_id uuid;
BEGIN
  IF v_caja IS NULL THEN RAISE EXCEPTION 'No hay una caja abierta: abre la caja para registrar movimientos.'; END IF;
  IF p_tipo NOT IN ('INGRESO', 'EGRESO') THEN RAISE EXCEPTION 'Tipo de movimiento no válido.'; END IF;
  IF p_monto IS NULL OR p_monto <= 0 THEN RAISE EXCEPTION 'El monto debe ser mayor a cero.'; END IF;
  IF length(trim(COALESCE(p_descripcion, ''))) < 3 THEN RAISE EXCEPTION 'Indica el motivo o descripción del movimiento.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.metodos_pago WHERE codigo = p_metodo AND activo) THEN
    RAISE EXCEPTION 'Método de pago no válido.';
  END IF;
  IF p_tipo = 'EGRESO' AND EXISTS (SELECT 1 FROM public.metodos_pago WHERE codigo = p_metodo AND es_efectivo)
     AND p_monto > public.efectivo_esperado(v_caja) THEN
    RAISE EXCEPTION 'No hay suficiente efectivo en la caja para ese egreso.';
  END IF;
  INSERT INTO public.caja_movimientos (caja_id, tipo, origen, monto, metodo, descripcion, registrado_por)
  VALUES (v_caja, p_tipo, COALESCE(p_origen, 'MANUAL'), p_monto, p_metodo, trim(p_descripcion), p_usuario)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.anular_movimiento_caja(p_movimiento uuid, p_motivo text, p_usuario uuid)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE m public.caja_movimientos%ROWTYPE;
BEGIN
  IF length(trim(COALESCE(p_motivo, ''))) < 3 THEN RAISE EXCEPTION 'Indica el motivo de la anulación.'; END IF;
  SELECT * INTO m FROM public.caja_movimientos WHERE id = p_movimiento FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Movimiento no encontrado.'; END IF;
  IF m.anulado THEN RAISE EXCEPTION 'El movimiento ya está anulado.'; END IF;
  IF m.pago_id IS NOT NULL THEN RAISE EXCEPTION 'Este ingreso viene de un pago: anula el pago desde la ficha del paciente.'; END IF;
  IF m.liquidacion_id IS NOT NULL THEN RAISE EXCEPTION 'Este egreso es el pago de una liquidación: no se anula desde la caja.'; END IF;
  UPDATE public.caja_movimientos
     SET anulado = true, motivo_anulacion = trim(p_motivo), anulado_por = p_usuario, anulado_en = now()
   WHERE id = p_movimiento;
END;
$$;

CREATE OR REPLACE FUNCTION public.cerrar_caja(p_caja uuid, p_contado integer, p_usuario uuid, p_justificacion text DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
  c public.cajas%ROWTYPE;
  v_esperado integer;
  v_diferencia integer;
BEGIN
  SELECT * INTO c FROM public.cajas WHERE id = p_caja FOR UPDATE;
  IF NOT FOUND OR c.estado <> 'ABIERTA' THEN RAISE EXCEPTION 'La caja no existe o ya está cerrada.'; END IF;
  IF p_contado IS NULL OR p_contado < 0 THEN RAISE EXCEPTION 'Ingresa el efectivo contado en el arqueo.'; END IF;
  v_esperado := public.efectivo_esperado(p_caja);
  v_diferencia := p_contado - v_esperado;
  IF v_diferencia <> 0 AND length(trim(COALESCE(p_justificacion, ''))) = 0 THEN
    RAISE EXCEPTION '%', 'Hay una diferencia de ' || public.pesos(v_diferencia) || ': debes justificarla.';
  END IF;
  UPDATE public.cajas
     SET estado = 'CERRADA', cerrada_por = p_usuario, cerrada_en = now(), monto_esperado = v_esperado,
         monto_contado = p_contado, diferencia = v_diferencia, justificacion = NULLIF(trim(p_justificacion), '')
   WHERE id = p_caja;
  RETURN v_diferencia;
END;
$$;

-- Resumen por período (para el historial): ingresos y egresos por método
CREATE OR REPLACE FUNCTION public.resumen_caja(p_desde date, p_hasta date)
RETURNS TABLE (metodo text, nombre text, ingresos bigint, egresos bigint, cantidad bigint)
LANGUAGE sql STABLE AS $$
  SELECT m.metodo, mp.nombre,
         COALESCE(sum(m.monto) FILTER (WHERE m.tipo = 'INGRESO'), 0),
         COALESCE(sum(m.monto) FILTER (WHERE m.tipo = 'EGRESO'), 0),
         count(*)
    FROM public.caja_movimientos m JOIN public.metodos_pago mp ON mp.codigo = m.metodo
   WHERE NOT m.anulado
     AND (m.created_at AT TIME ZONE 'America/Santiago')::date BETWEEN p_desde AND p_hasta
   GROUP BY m.metodo, mp.nombre, mp.orden
   ORDER BY mp.orden;
$$;


-- =====================================================================
-- 4. PAGOS ↔ CAJA (registrar y anular en la misma operación)
-- =====================================================================
CREATE OR REPLACE FUNCTION public.registrar_pago(
  p_paciente   uuid,
  p_monto      integer,
  p_metodo     text,
  p_detalle    jsonb,
  p_usuario    uuid,
  p_referencia text DEFAULT NULL,
  p_boleta     text DEFAULT NULL,
  p_nota       text DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE
  v_id uuid;
  v_numero bigint;
  v_suma integer;
  v_item public.presupuesto_items%ROWTYPE;
  v_nombre text;
  v_trat_estado text;
  v_metodo public.metodos_pago%ROWTYPE;
  v_caja uuid := public.caja_abierta();
  v_paciente text;
  r record;
BEGIN
  IF p_monto IS NULL OR p_monto <= 0 THEN RAISE EXCEPTION 'El monto debe ser mayor a cero.'; END IF;
  SELECT nombres || ' ' || apellidos INTO v_paciente FROM public.pacientes WHERE id = p_paciente;
  IF NOT FOUND THEN RAISE EXCEPTION 'Paciente no encontrado.'; END IF;

  SELECT * INTO v_metodo FROM public.metodos_pago WHERE codigo = p_metodo AND activo;
  IF NOT FOUND THEN RAISE EXCEPTION 'Método de pago no válido o desactivado.'; END IF;
  IF v_metodo.pide_referencia AND length(trim(COALESCE(p_referencia, ''))) = 0 THEN
    RAISE EXCEPTION '%', 'Ingresa el N° de operación o comprobante (' || v_metodo.nombre || ').';
  END IF;
  -- Regla: todo método que entra a caja (efectivo, débito, crédito, transferencia, cheque…)
  -- exige una caja abierta. Solo los marcados "no entra a caja" (ej. Bono FONASA) quedan fuera.
  IF v_metodo.registra_en_caja AND v_caja IS NULL THEN
    RAISE EXCEPTION '%', 'No hay una caja abierta: para recibir un pago con ' || v_metodo.nombre || ' abre la caja en el módulo Caja.';
  END IF;

  IF p_detalle IS NULL OR jsonb_typeof(p_detalle) <> 'array' OR jsonb_array_length(p_detalle) = 0 THEN
    RAISE EXCEPTION 'Indica a qué prestaciones se aplica el pago.';
  END IF;
  SELECT COALESCE(sum((e ->> 'monto')::integer), 0) INTO v_suma FROM jsonb_array_elements(p_detalle) e;
  IF v_suma <> p_monto THEN
    RAISE EXCEPTION '%', 'La distribución ($' || v_suma || ') no coincide con el monto del pago ($' || p_monto || ').';
  END IF;

  INSERT INTO public.pagos (paciente_id, monto, metodo, referencia, numero_boleta, nota, registrado_por)
  VALUES (p_paciente, p_monto, p_metodo, NULLIF(trim(p_referencia), ''), NULLIF(trim(p_boleta), ''), NULLIF(trim(p_nota), ''), p_usuario)
  RETURNING id, numero INTO v_id, v_numero;

  FOR r IN SELECT (e ->> 'item_id')::uuid AS item_id, (e ->> 'monto')::integer AS monto FROM jsonb_array_elements(p_detalle) e LOOP
    IF r.monto IS NULL OR r.monto <= 0 THEN RAISE EXCEPTION 'Cada monto aplicado debe ser mayor a cero.'; END IF;
    SELECT * INTO v_item FROM public.presupuesto_items WHERE id = r.item_id FOR UPDATE;
    IF NOT FOUND OR v_item.paciente_id <> p_paciente THEN RAISE EXCEPTION 'Una de las prestaciones no pertenece al paciente.'; END IF;
    v_nombre := (SELECT nombre FROM public.prestaciones WHERE id = v_item.prestacion_id);
    v_trat_estado := (SELECT estado FROM public.presupuestos WHERE id = v_item.presupuesto_id);
    IF v_item.estado = 'ANULADO' OR v_trat_estado = 'ANULADO' THEN
      RAISE EXCEPTION '%', 'No se puede pagar "' || v_nombre || '": está anulada.';
    END IF;
    IF r.monto > v_item.precio - v_item.abonado THEN
      RAISE EXCEPTION '%', 'El abono a "' || v_nombre || '" supera su saldo ($' || (v_item.precio - v_item.abonado) || ').';
    END IF;
    INSERT INTO public.pago_detalle (pago_id, item_id, monto) VALUES (v_id, r.item_id, r.monto);
    UPDATE public.presupuesto_items SET abonado = abonado + r.monto WHERE id = r.item_id;
  END LOOP;

  -- Ingreso automático en la caja abierta
  IF v_caja IS NOT NULL AND v_metodo.registra_en_caja THEN
    INSERT INTO public.caja_movimientos (caja_id, tipo, origen, monto, metodo, descripcion, pago_id, registrado_por)
    VALUES (v_caja, 'INGRESO', 'PAGO', p_monto, p_metodo, 'Pago N° ' || v_numero || ' · ' || v_paciente, v_id, p_usuario);
  END IF;

  PERFORM public.registrar_evento(p_paciente, 'PAGO', 'CREADO',
    'Pago N° ' || v_numero || ' · ' || public.pesos(p_monto),
    v_metodo.nombre || COALESCE(' · Ref. ' || NULLIF(trim(p_referencia), ''), '') || COALESCE(' · Boleta ' || NULLIF(trim(p_boleta), ''), ''),
    NULL, 'pagos', v_id, NULL, p_usuario);

  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.anular_pago(p_pago uuid, p_usuario uuid, p_motivo text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  v_pago public.pagos%ROWTYPE;
  v_liq bigint;
  v_mov public.caja_movimientos%ROWTYPE;
  v_estado_caja text;
  v_caja uuid := public.caja_abierta();
  d record;
BEGIN
  IF length(trim(COALESCE(p_motivo, ''))) < 3 THEN RAISE EXCEPTION 'Indica el motivo de la anulación.'; END IF;
  SELECT * INTO v_pago FROM public.pagos WHERE id = p_pago FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Pago no encontrado.'; END IF;
  IF v_pago.estado <> 'VIGENTE' THEN RAISE EXCEPTION 'El pago ya está anulado.'; END IF;

  SELECT l.numero INTO v_liq
    FROM public.pago_detalle pd
    JOIN public.liquidacion_detalle ld ON ld.item_id = pd.item_id AND ld.vigente
    JOIN public.liquidaciones l ON l.id = ld.liquidacion_id
   WHERE pd.pago_id = p_pago LIMIT 1;
  IF v_liq IS NOT NULL THEN
    RAISE EXCEPTION '%', 'No se puede anular: este pago cubre prestaciones ya liquidadas al profesional (liquidación N° ' || v_liq || '). Si la liquidación aún no se paga, anúlala primero.';
  END IF;

  -- Caja: si el movimiento está en la caja abierta se anula; si esa caja ya cerró, se registra un egreso de ajuste
  SELECT * INTO v_mov FROM public.caja_movimientos WHERE pago_id = p_pago AND NOT anulado LIMIT 1;
  IF FOUND THEN
    SELECT estado INTO v_estado_caja FROM public.cajas WHERE id = v_mov.caja_id;
    IF v_estado_caja = 'ABIERTA' THEN
      UPDATE public.caja_movimientos
         SET anulado = true, motivo_anulacion = 'Pago anulado: ' || trim(p_motivo), anulado_por = p_usuario, anulado_en = now()
       WHERE id = v_mov.id;
    ELSE
      IF v_caja IS NULL THEN
        RAISE EXCEPTION 'Ese pago entró en una caja ya cerrada: abre una caja para registrar la devolución.';
      ELSE
        INSERT INTO public.caja_movimientos (caja_id, tipo, origen, monto, metodo, descripcion, pago_id, registrado_por)
        VALUES (v_caja, 'EGRESO', 'AJUSTE', v_pago.monto, v_pago.metodo,
                'Anulación pago N° ' || v_pago.numero || ' (caja N° ' || (SELECT numero FROM public.cajas WHERE id = v_mov.caja_id) || '): ' || trim(p_motivo),
                p_pago, p_usuario);
      END IF;
    END IF;
  END IF;

  FOR d IN SELECT item_id, monto FROM public.pago_detalle WHERE pago_id = p_pago LOOP
    UPDATE public.presupuesto_items SET abonado = abonado - d.monto WHERE id = d.item_id;
  END LOOP;

  UPDATE public.pagos
     SET estado = 'ANULADO', anulado_por = p_usuario, fecha_anulacion = now(), motivo_anulacion = trim(p_motivo)
   WHERE id = p_pago;

  PERFORM public.registrar_evento(v_pago.paciente_id, 'PAGO', 'ANULADO',
    'Pago N° ' || v_pago.numero || ' anulado · ' || public.pesos(v_pago.monto),
    trim(p_motivo), NULL, 'pagos', p_pago, NULL, p_usuario);
END;
$$;


