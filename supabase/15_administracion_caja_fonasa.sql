-- Crear el convenio crea también su arancel (con el % de descuento sobre el arancel base)
CREATE OR REPLACE FUNCTION public.crear_convenio(
  p_nombre text, p_institucion text, p_tipo text, p_descuento numeric, p_inicio date, p_usuario uuid,
  p_fin date DEFAULT NULL, p_rut text DEFAULT NULL, p_contacto text DEFAULT NULL, p_condiciones text DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE
  v_arancel uuid;
  v_id uuid;
BEGIN
  IF length(trim(COALESCE(p_nombre, ''))) = 0 OR length(trim(COALESCE(p_institucion, ''))) = 0 THEN
    RAISE EXCEPTION 'Nombre e institución son obligatorios.';
  END IF;
  IF p_inicio IS NULL THEN RAISE EXCEPTION 'Indica la fecha de inicio de vigencia.'; END IF;
  IF p_descuento IS NULL OR p_descuento < 0 OR p_descuento > 100 THEN RAISE EXCEPTION 'El descuento debe estar entre 0 y 100%%.'; END IF;
  PERFORM set_config('app.usuario', COALESCE(p_usuario::text, ''), true);
  BEGIN
    INSERT INTO public.aranceles (nombre, tipo, descripcion, porcentaje_descuento)
    VALUES ('Convenio ' || trim(p_nombre), 'CONVENIO', 'Arancel del convenio ' || trim(p_nombre) || ' (' || trim(p_institucion) || ')', p_descuento)
    RETURNING id INTO v_arancel;
    INSERT INTO public.convenios (nombre, institucion, tipo, rut_institucion, contacto, porcentaje_descuento, arancel_id,
                                  fecha_inicio, fecha_fin, condiciones, creado_por)
    VALUES (trim(p_nombre), trim(p_institucion), COALESCE(p_tipo, 'EMPRESA'), NULLIF(trim(p_rut), ''), NULLIF(trim(p_contacto), ''),
            p_descuento, v_arancel, p_inicio, p_fin, NULLIF(trim(p_condiciones), ''), p_usuario)
    RETURNING id INTO v_id;
  EXCEPTION WHEN unique_violation THEN
    RAISE EXCEPTION '%', 'Ya existe un convenio o arancel llamado "' || trim(p_nombre) || '".';
  END;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.actualizar_convenio(
  p_convenio uuid, p_descuento numeric, p_fin date, p_activo boolean, p_condiciones text, p_usuario uuid
) RETURNS void LANGUAGE plpgsql AS $$
DECLARE c public.convenios%ROWTYPE;
BEGIN
  SELECT * INTO c FROM public.convenios WHERE id = p_convenio FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Convenio no encontrado.'; END IF;
  IF p_descuento IS NULL OR p_descuento < 0 OR p_descuento > 100 THEN RAISE EXCEPTION 'El descuento debe estar entre 0 y 100%%.'; END IF;
  IF p_fin IS NOT NULL AND p_fin < c.fecha_inicio THEN RAISE EXCEPTION 'La fecha de término no puede ser anterior al inicio.'; END IF;
  PERFORM set_config('app.usuario', COALESCE(p_usuario::text, ''), true);
  UPDATE public.convenios
     SET porcentaje_descuento = p_descuento, fecha_fin = p_fin, activo = p_activo, condiciones = NULLIF(trim(p_condiciones), '')
   WHERE id = p_convenio;
  UPDATE public.aranceles SET porcentaje_descuento = p_descuento, activo = p_activo WHERE id = c.arancel_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.agregar_beneficiario(p_convenio uuid, p_paciente uuid, p_usuario uuid)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE c public.convenios%ROWTYPE;
BEGIN
  SELECT * INTO c FROM public.convenios WHERE id = p_convenio;
  IF NOT FOUND OR NOT public.convenio_vigente(c) THEN RAISE EXCEPTION 'El convenio no está vigente.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.pacientes WHERE id = p_paciente AND activo) THEN RAISE EXCEPTION 'Paciente no encontrado o deshabilitado.'; END IF;
  INSERT INTO public.convenio_beneficiarios (convenio_id, paciente_id, agregado_por) VALUES (p_convenio, p_paciente, p_usuario)
  ON CONFLICT (convenio_id, paciente_id) DO UPDATE SET activo = true;
END;
$$;

-- Regla: solo puede usar el arancel de un convenio quien sea beneficiario de ese convenio vigente
CREATE OR REPLACE FUNCTION public.presupuestos_validar_convenio()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE c public.convenios%ROWTYPE;
BEGIN
  SELECT * INTO c FROM public.convenios WHERE arancel_id = NEW.arancel_id;
  IF FOUND THEN
    IF NOT public.convenio_vigente(c) THEN
      RAISE EXCEPTION '%', 'El convenio "' || c.nombre || '" no está vigente.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.convenio_beneficiarios
                    WHERE convenio_id = c.id AND paciente_id = NEW.paciente_id AND activo) THEN
      RAISE EXCEPTION '%', 'El paciente no es beneficiario del convenio "' || c.nombre || '".';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS presupuestos_validar_convenio_trg ON public.presupuestos;
CREATE TRIGGER presupuestos_validar_convenio_trg BEFORE INSERT ON public.presupuestos
  FOR EACH ROW EXECUTE FUNCTION public.presupuestos_validar_convenio();

-- Arancel sugerido: convenio vigente del paciente → FONASA → base
CREATE OR REPLACE FUNCTION public.arancel_paciente(p_paciente uuid)
RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT COALESCE(
    (SELECT c.arancel_id FROM public.convenio_beneficiarios b JOIN public.convenios c ON c.id = b.convenio_id
      WHERE b.paciente_id = p_paciente AND b.activo AND public.convenio_vigente(c)
      ORDER BY c.porcentaje_descuento DESC LIMIT 1),
    (SELECT a.id FROM public.aranceles a JOIN public.pacientes p ON p.id = p_paciente
      WHERE a.activo AND a.tipo = 'FONASA' AND p.prevision ILIKE 'FONASA%'
      ORDER BY a.created_at LIMIT 1),
    (SELECT id FROM public.aranceles WHERE es_base)
  );
$$;

-- Contrato en cuotas: la suma de las cuotas debe ser igual al monto pactado
-- p_cuotas: [{"monto": 50000, "vencimiento": "2026-11-05"}, ...]
CREATE OR REPLACE FUNCTION public.crear_contrato_cuotas(
  p_convenio uuid, p_paciente uuid, p_total integer, p_cuotas jsonb, p_usuario uuid,
  p_presupuesto uuid DEFAULT NULL, p_nota text DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE
  c public.convenios%ROWTYPE;
  v_id uuid;
  v_suma integer;
  v_n integer;
  q record;
BEGIN
  SELECT * INTO c FROM public.convenios WHERE id = p_convenio;
  IF NOT FOUND OR NOT public.convenio_vigente(c) THEN RAISE EXCEPTION 'El convenio no está vigente.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.convenio_beneficiarios WHERE convenio_id = p_convenio AND paciente_id = p_paciente AND activo) THEN
    RAISE EXCEPTION 'El paciente no es beneficiario de este convenio.';
  END IF;
  IF p_total IS NULL OR p_total <= 0 THEN RAISE EXCEPTION 'El monto pactado debe ser mayor a cero.'; END IF;
  IF p_cuotas IS NULL OR jsonb_typeof(p_cuotas) <> 'array' OR jsonb_array_length(p_cuotas) = 0 THEN
    RAISE EXCEPTION 'Agrega al menos una cuota.';
  END IF;
  v_n := jsonb_array_length(p_cuotas);
  SELECT COALESCE(sum((e ->> 'monto')::integer), 0) INTO v_suma FROM jsonb_array_elements(p_cuotas) e;
  IF v_suma <> p_total THEN
    RAISE EXCEPTION '%', 'La suma de las cuotas (' || public.pesos(v_suma) || ') no coincide con el monto pactado (' || public.pesos(p_total) || ').';
  END IF;
  IF p_presupuesto IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.presupuestos WHERE id = p_presupuesto AND paciente_id = p_paciente) THEN
    RAISE EXCEPTION 'El tratamiento no pertenece al paciente.';
  END IF;

  INSERT INTO public.convenio_contratos (convenio_id, paciente_id, presupuesto_id, monto_total, cantidad_cuotas, nota, creado_por)
  VALUES (p_convenio, p_paciente, p_presupuesto, p_total, v_n, NULLIF(trim(p_nota), ''), p_usuario)
  RETURNING id INTO v_id;

  FOR q IN SELECT row_number() OVER (ORDER BY (e ->> 'vencimiento')::date) AS n, (e ->> 'monto')::integer AS monto, (e ->> 'vencimiento')::date AS venc
             FROM jsonb_array_elements(p_cuotas) e LOOP
    IF q.monto IS NULL OR q.monto <= 0 THEN RAISE EXCEPTION 'Cada cuota debe ser mayor a cero.'; END IF;
    IF q.venc IS NULL THEN RAISE EXCEPTION 'Cada cuota necesita fecha de vencimiento.'; END IF;
    INSERT INTO public.convenio_cuotas (contrato_id, numero, monto, vencimiento) VALUES (v_id, q.n, q.monto, q.venc);
  END LOOP;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.pagar_cuota(p_cuota uuid, p_metodo text, p_usuario uuid, p_referencia text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  q public.convenio_cuotas%ROWTYPE;
  m public.metodos_pago%ROWTYPE;
  v_caja uuid := public.caja_abierta();
  v_desc text;
BEGIN
  SELECT * INTO q FROM public.convenio_cuotas WHERE id = p_cuota FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Cuota no encontrada.'; END IF;
  IF q.pagada_en IS NOT NULL THEN RAISE EXCEPTION 'La cuota ya está pagada.'; END IF;
  SELECT * INTO m FROM public.metodos_pago WHERE codigo = p_metodo AND activo;
  IF NOT FOUND THEN RAISE EXCEPTION 'Método de pago no válido.'; END IF;
  IF m.pide_referencia AND length(trim(COALESCE(p_referencia, ''))) = 0 THEN RAISE EXCEPTION 'Ingresa el N° de operación.'; END IF;
  IF m.registra_en_caja AND v_caja IS NULL THEN
    RAISE EXCEPTION '%', 'No hay una caja abierta: para recibir un pago con ' || m.nombre || ' abre la caja en el módulo Caja.';
  END IF;

  UPDATE public.convenio_cuotas
     SET pagada_en = now(), metodo = p_metodo, referencia = NULLIF(trim(p_referencia), ''), registrado_por = p_usuario
   WHERE id = p_cuota;

  IF v_caja IS NOT NULL AND m.registra_en_caja THEN
    SELECT 'Cuota ' || q.numero || '/' || ct.cantidad_cuotas || ' · contrato N° ' || ct.numero || ' · ' || cv.nombre
      INTO v_desc
      FROM public.convenio_contratos ct JOIN public.convenios cv ON cv.id = ct.convenio_id WHERE ct.id = q.contrato_id;
    INSERT INTO public.caja_movimientos (caja_id, tipo, origen, monto, metodo, descripcion, registrado_por)
    VALUES (v_caja, 'INGRESO', 'CUOTA_CONVENIO', q.monto, p_metodo, v_desc, p_usuario);
  END IF;
END;
$$;

