CREATE OR REPLACE FUNCTION public.actualizar_parametro(p_clave text, p_valor text, p_usuario uuid)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  p public.parametros_sistema%ROWTYPE;
  v numeric;
BEGIN
  SELECT * INTO p FROM public.parametros_sistema WHERE clave = p_clave FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Parámetro no encontrado.'; END IF;
  IF p.tipo IN ('ENTERO', 'PORCENTAJE') THEN
    IF trim(p_valor) !~ '^-?\d+(\.\d+)?$' THEN RAISE EXCEPTION 'El valor debe ser numérico.'; END IF;
    v := trim(p_valor)::numeric;
    IF p.tipo = 'ENTERO' AND v <> trunc(v) THEN RAISE EXCEPTION 'El valor debe ser un número entero.'; END IF;
    IF (p.minimo IS NOT NULL AND v < p.minimo) OR (p.maximo IS NOT NULL AND v > p.maximo) THEN
      RAISE EXCEPTION '%', 'El valor debe estar entre ' || p.minimo || ' y ' || p.maximo || '.';
    END IF;
  END IF;
  PERFORM set_config('app.usuario', COALESCE(p_usuario::text, ''), true);
  UPDATE public.parametros_sistema SET valor = trim(p_valor), updated_at = now() WHERE clave = p_clave;
END;
$$;


