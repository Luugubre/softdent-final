-- Crear / editar / activar un catálogo (con usuario para la auditoría)
CREATE OR REPLACE FUNCTION public.guardar_catalogo(
  p_tabla       text,
  p_id          uuid,
  p_nombre      text,
  p_usuario     uuid,
  p_descripcion text DEFAULT NULL,
  p_activo      boolean DEFAULT true,
  p_extra       jsonb DEFAULT '{}'::jsonb   -- tipo (previsiones) / duracion_min (tipos_atencion)
) RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE
  v_id uuid := p_id;
  v_nombre text := trim(COALESCE(p_nombre, ''));
BEGIN
  IF p_tabla NOT IN ('especialidades', 'categorias_prestaciones', 'boxes', 'previsiones', 'tipos_atencion') THEN
    RAISE EXCEPTION 'Catálogo no válido.';
  END IF;
  IF length(v_nombre) = 0 THEN RAISE EXCEPTION 'El nombre es obligatorio.'; END IF;
  PERFORM set_config('app.usuario', COALESCE(p_usuario::text, ''), true);

  BEGIN
    IF v_id IS NULL THEN
      EXECUTE format('INSERT INTO public.%I (nombre) VALUES ($1) RETURNING id', p_tabla) INTO v_id USING v_nombre;
    ELSE
      EXECUTE format('UPDATE public.%I SET nombre = $1, activo = $2 WHERE id = $3', p_tabla) USING v_nombre, COALESCE(p_activo, true), v_id;
    END IF;
  EXCEPTION WHEN unique_violation THEN
    RAISE EXCEPTION '%', 'Ya existe un registro llamado "' || v_nombre || '".';
  END;

  IF p_tabla = 'especialidades' THEN
    UPDATE public.especialidades SET descripcion = NULLIF(trim(p_descripcion), '') WHERE id = v_id;
  ELSIF p_tabla = 'previsiones' AND p_extra ? 'tipo' THEN
    UPDATE public.previsiones SET tipo = p_extra ->> 'tipo' WHERE id = v_id;
  ELSIF p_tabla = 'tipos_atencion' AND p_extra ? 'duracion_min' THEN
    UPDATE public.tipos_atencion SET duracion_min = (p_extra ->> 'duracion_min')::int WHERE id = v_id;
  END IF;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.guardar_metodo_pago(
  p_codigo text, p_nombre text, p_es_efectivo boolean, p_pide_referencia boolean,
  p_registra_en_caja boolean, p_activo boolean, p_usuario uuid, p_nuevo boolean DEFAULT false
) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF length(trim(COALESCE(p_nombre, ''))) = 0 THEN RAISE EXCEPTION 'El nombre es obligatorio.'; END IF;
  PERFORM set_config('app.usuario', COALESCE(p_usuario::text, ''), true);
  BEGIN
    IF p_nuevo THEN
      INSERT INTO public.metodos_pago (codigo, nombre, es_efectivo, pide_referencia, registra_en_caja, orden)
      VALUES (upper(trim(p_codigo)), trim(p_nombre), p_es_efectivo, p_pide_referencia, p_registra_en_caja,
              (SELECT COALESCE(max(orden), 0) + 1 FROM public.metodos_pago));
    ELSE
      UPDATE public.metodos_pago
         SET nombre = trim(p_nombre), es_efectivo = p_es_efectivo, pide_referencia = p_pide_referencia,
             registra_en_caja = p_registra_en_caja, activo = p_activo
       WHERE codigo = p_codigo;
      IF NOT FOUND THEN RAISE EXCEPTION 'Método de pago no encontrado.'; END IF;
    END IF;
  EXCEPTION
    WHEN unique_violation THEN RAISE EXCEPTION 'Ya existe un método de pago con ese código o nombre.';
    WHEN check_violation THEN RAISE EXCEPTION 'El código debe tener solo letras mayúsculas y guion bajo (ej: CHEQUE).';
  END;
END;
$$;


