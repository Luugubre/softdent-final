-- Montos en formato chileno: 15000 → $15.000
CREATE OR REPLACE FUNCTION public.pesos(n integer)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN n < 0 THEN '-$' ELSE '$' END || replace(to_char(abs(n), 'FM999G999G999'), ',', '.');
$$;

