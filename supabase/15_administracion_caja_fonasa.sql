-- Liquidación del mes: toma todo lo liquidable pendiente hasta el fin del período
CREATE OR REPLACE FUNCTION public.generar_liquidacion(
  p_profesional  uuid,
  p_periodo      text,          -- 'YYYY-MM'
  p_usuario      uuid,
  p_bonificacion integer DEFAULT 0,
  p_ajuste       integer DEFAULT 0,
  p_descuento    integer DEFAULT 0,
  p_nota         text DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE
  v_pct numeric(5,2);
  v_id uuid;
  v_cantidad integer;
  v_inicio date;
  v_corte date;
  v_base integer;
  v_prof integer;
  v_total integer;
BEGIN
  IF p_periodo IS NULL OR p_periodo !~ '^\d{4}-(0[1-9]|1[0-2])$' THEN RAISE EXCEPTION 'Período no válido (formato AAAA-MM).'; END IF;
  v_inicio := (p_periodo || '-01')::date;
  IF v_inicio > public.hoy_chile() THEN RAISE EXCEPTION 'No se puede liquidar un mes futuro.'; END IF;
  v_corte := LEAST((v_inicio + interval '1 month - 1 day')::date, public.hoy_chile());
  IF COALESCE(p_bonificacion, 0) < 0 OR COALESCE(p_descuento, 0) < 0 THEN
    RAISE EXCEPTION 'La bonificación y el descuento no pueden ser negativos (usa el ajuste para restar).';
  END IF;

  SELECT porcentaje_liquidacion INTO v_pct FROM public.perfiles WHERE id = p_profesional FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Profesional no encontrado.'; END IF;
  IF v_pct IS NULL THEN RAISE EXCEPTION 'El profesional no tiene configurado su porcentaje de liquidación.'; END IF;
  IF EXISTS (SELECT 1 FROM public.liquidaciones WHERE profesional_id = p_profesional AND periodo = p_periodo AND estado <> 'ANULADA') THEN
    RAISE EXCEPTION '%', 'Ya existe una liquidación de ' || p_periodo || ' para este profesional. Las correcciones van como ajuste en el mes siguiente.';
  END IF;

  INSERT INTO public.liquidaciones (profesional_id, periodo, fecha_corte, porcentaje, porcentaje_clinica, nota, creado_por, estado)
  VALUES (p_profesional, p_periodo, v_corte, v_pct, 100 - v_pct, NULLIF(trim(p_nota), ''), p_usuario, 'CALCULADA')
  RETURNING id INTO v_id;

  INSERT INTO public.liquidacion_detalle
    (liquidacion_id, avance_id, item_id, paciente_id, paciente_nombre, prestacion_nombre, pieza, tramo,
     fecha_realizado, fecha_pagado, monto_base, porcentaje, monto)
  SELECT v_id, v.avance_id, v.item_id, v.paciente_id, v.paciente_nombre, v.prestacion_nombre, v.pieza,
         v.progreso_anterior || '% → ' || v.progreso_nuevo || '%',
         v.completado_en, v.fecha_pagado, v.monto_base, v_pct, round(v.monto_base * v_pct / 100.0)::int
    FROM public.v_produccion_profesional v
   WHERE v.profesional_id = p_profesional AND v.liquidable AND v.liquidacion_id IS NULL
     AND (v.fecha_liquidable AT TIME ZONE 'America/Santiago')::date <= v_corte;
  GET DIAGNOSTICS v_cantidad = ROW_COUNT;

  IF v_cantidad = 0 AND COALESCE(p_bonificacion, 0) = 0 AND COALESCE(p_ajuste, 0) = 0 THEN
    RAISE EXCEPTION 'No hay prestaciones terminadas y pagadas pendientes de liquidar en ese período.';
  END IF;

  SELECT COALESCE(sum(monto_base), 0), COALESCE(sum(monto), 0) INTO v_base, v_prof FROM public.liquidacion_detalle WHERE liquidacion_id = v_id;
  v_total := v_prof + COALESCE(p_bonificacion, 0) + COALESCE(p_ajuste, 0) - COALESCE(p_descuento, 0);
  IF v_total < 0 THEN RAISE EXCEPTION 'El total a pagar quedaría negativo: revisa el ajuste y el descuento.'; END IF;

  UPDATE public.liquidaciones
     SET cantidad = v_cantidad, total_base = v_base, base_profesional = v_prof,
         bonificacion = COALESCE(p_bonificacion, 0), ajuste = COALESCE(p_ajuste, 0), descuento = COALESCE(p_descuento, 0),
         total = v_total, total_clinica = v_base - v_prof
   WHERE id = v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.aprobar_liquidacion(p_liquidacion uuid, p_usuario uuid)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_estado text;
BEGIN
  SELECT estado INTO v_estado FROM public.liquidaciones WHERE id = p_liquidacion FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Liquidación no encontrada.'; END IF;
  IF v_estado <> 'CALCULADA' THEN RAISE EXCEPTION 'Solo se puede aprobar una liquidación calculada.'; END IF;
  UPDATE public.liquidaciones SET estado = 'APROBADA', aprobado_por = p_usuario, fecha_aprobacion = now() WHERE id = p_liquidacion;
END;
$$;

CREATE OR REPLACE FUNCTION public.pagar_liquidacion(p_liquidacion uuid, p_usuario uuid, p_metodo text, p_referencia text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  l public.liquidaciones%ROWTYPE;
  v_caja uuid := public.caja_abierta();
BEGIN
  SELECT * INTO l FROM public.liquidaciones WHERE id = p_liquidacion FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Liquidación no encontrada.'; END IF;
  IF l.estado <> 'APROBADA' THEN RAISE EXCEPTION 'La liquidación debe estar aprobada antes de pagarla.'; END IF;
  IF p_metodo NOT IN ('TRANSFERENCIA', 'EFECTIVO', 'CHEQUE') THEN RAISE EXCEPTION 'Método de pago no válido.'; END IF;
  IF p_metodo <> 'EFECTIVO' AND length(trim(COALESCE(p_referencia, ''))) = 0 THEN
    RAISE EXCEPTION 'Ingresa el N° de operación o de cheque.';
  END IF;

  -- Pagar en efectivo saca la plata de la caja
  IF p_metodo = 'EFECTIVO' THEN
    IF v_caja IS NULL THEN RAISE EXCEPTION 'Para pagar en efectivo debe haber una caja abierta.'; END IF;
    IF l.total > public.efectivo_esperado(v_caja) THEN RAISE EXCEPTION 'No hay suficiente efectivo en la caja.'; END IF;
    INSERT INTO public.caja_movimientos (caja_id, tipo, origen, monto, metodo, descripcion, liquidacion_id, registrado_por)
    VALUES (v_caja, 'EGRESO', 'LIQUIDACION', l.total, 'EFECTIVO',
            'Liquidación N° ' || l.numero || ' · ' || public.nombre_usuario(l.profesional_id) || ' · ' || COALESCE(l.periodo, ''),
            p_liquidacion, p_usuario);
  END IF;

  UPDATE public.liquidaciones
     SET estado = 'PAGADA', pagado_por = p_usuario, fecha_pago = now(),
         metodo_pago = p_metodo, referencia_pago = NULLIF(trim(p_referencia), '')
   WHERE id = p_liquidacion;
END;
$$;

CREATE OR REPLACE FUNCTION public.anular_liquidacion(p_liquidacion uuid, p_usuario uuid, p_motivo text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_estado text;
BEGIN
  IF length(trim(COALESCE(p_motivo, ''))) < 3 THEN RAISE EXCEPTION 'Indica el motivo de la anulación.'; END IF;
  SELECT estado INTO v_estado FROM public.liquidaciones WHERE id = p_liquidacion FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Liquidación no encontrada.'; END IF;
  IF v_estado = 'PAGADA' THEN RAISE EXCEPTION 'Una liquidación pagada no se puede anular: corrige con un ajuste en el mes siguiente.'; END IF;
  IF v_estado = 'ANULADA' THEN RAISE EXCEPTION 'La liquidación ya está anulada.'; END IF;
  UPDATE public.liquidacion_detalle SET vigente = false WHERE liquidacion_id = p_liquidacion;
  UPDATE public.liquidaciones
     SET estado = 'ANULADA', anulado_por = p_usuario, fecha_anulacion = now(), motivo_anulacion = trim(p_motivo)
   WHERE id = p_liquidacion;
END;
$$;


