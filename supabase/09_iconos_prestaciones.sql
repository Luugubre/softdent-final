UPDATE public.prestaciones SET icono = CASE
    WHEN nombre ILIKE '%implante%' AND nombre ILIKE '%corona%' THEN 'implante_corona'
    WHEN nombre ILIKE '%implante%' THEN 'implante'
    WHEN nombre ILIKE ANY (ARRAY['%endodoncia%','%conducto%','%pulpotom%','%pulpectom%']) THEN 'endodoncia'
    WHEN nombre ILIKE ANY (ARRAY['%perno%','%muñon%','%muñón%']) THEN 'perno'
    WHEN nombre ILIKE '%carilla%' THEN 'carilla'
    WHEN nombre ILIKE '%corona%' THEN 'corona'
    WHEN nombre ILIKE ANY (ARRAY['%incrustac%','%onlay%','%inlay%']) THEN 'incrustacion'
    WHEN nombre ILIKE ANY (ARRAY['%puente%','%fija%']) THEN 'fija'
    WHEN nombre ILIKE ANY (ARRAY['%removible%','%protesis%','%prótesis%','%placa%']) THEN 'removible'
    WHEN nombre ILIKE ANY (ARRAY['%cirug%','%compleja%','%tercer molar%','%cordal%']) THEN 'cirugia'
    WHEN nombre ILIKE ANY (ARRAY['%extracc%','%exodoncia%']) THEN 'extraccion'
    WHEN nombre ILIKE ANY (ARRAY['%ortodon%','%bracket%','%contenc%']) THEN 'ortodoncia'
    WHEN nombre ILIKE '%sellante%' THEN 'sellante'
    WHEN nombre ILIKE ANY (ARRAY['%limpieza%','%destartraje%','%profilaxis%','%pulido%']) THEN 'limpieza'
    WHEN nombre ILIKE '%blanquea%' THEN 'blanqueamiento'
    WHEN nombre ILIKE ANY (ARRAY['%radiograf%','% rx%','%panoram%','%scanner%','%cbct%']) THEN 'rayos'
    WHEN nombre ILIKE ANY (ARRAY['%resina%','%restaurac%','%obturac%','%ionomero%','%ionómero%','%amalgama%']) THEN 'restauracion'
    ELSE NULL END
 WHERE icono IS NULL;

SELECT icono, count(*) FROM public.prestaciones GROUP BY icono ORDER BY count(*) DESC;
