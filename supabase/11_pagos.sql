DROP TABLE IF EXISTS public.pago_detalle CASCADE;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
              WHERE table_schema = 'public' AND table_name = 'pagos' AND column_name = 'presupuesto_id') THEN
    DROP TABLE public.pagos CASCADE;
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.pagos (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  numero           bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  paciente_id      uuid NOT NULL REFERENCES public.pacientes(id) ON DELETE RESTRICT,
  monto            integer NOT NULL CHECK (monto > 0),
  metodo           text NOT NULL,
  referencia       text,
  numero_boleta    text,
  nota             text,
  estado           text NOT NULL DEFAULT 'VIGENTE',
  registrado_por   uuid REFERENCES public.perfiles(id) ON DELETE SET NULL,
  fecha            timestamptz NOT NULL DEFAULT now(),
  anulado_por      uuid REFERENCES public.perfiles(id) ON DELETE SET NULL,
  fecha_anulacion  timestamptz,
  motivo_anulacion text,

  CONSTRAINT pagos_metodo_chk CHECK (metodo IN ('EFECTIVO', 'DEBITO', 'CREDITO', 'TRANSFERENCIA')),
  CONSTRAINT pagos_estado_chk CHECK (estado IN ('VIGENTE', 'ANULADO')),
  CONSTRAINT pagos_referencia_chk CHECK (metodo = 'EFECTIVO' OR length(trim(COALESCE(referencia, ''))) > 0),
  CONSTRAINT pagos_anulacion_chk CHECK (estado = 'VIGENTE' OR (fecha_anulacion IS NOT NULL AND motivo_anulacion IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS pagos_paciente_idx ON public.pagos (paciente_id, fecha DESC);

CREATE TABLE IF NOT EXISTS public.pago_detalle (
  id      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  pago_id uuid NOT NULL REFERENCES public.pagos(id) ON DELETE RESTRICT,
  item_id uuid NOT NULL REFERENCES public.presupuesto_items(id) ON DELETE RESTRICT,
  monto   integer NOT NULL CHECK (monto > 0),
  UNIQUE (pago_id, item_id)
);

CREATE INDEX IF NOT EXISTS pago_detalle_item_idx ON public.pago_detalle (item_id);

ALTER TABLE public.pagos        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pago_detalle ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.pagos_proteger()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'Un pago no se elimina: se anula.'; END IF;
  IF OLD.estado = 'ANULADO'
     OR NEW.monto IS DISTINCT FROM OLD.monto OR NEW.metodo IS DISTINCT FROM OLD.metodo
     OR NEW.paciente_id IS DISTINCT FROM OLD.paciente_id OR NEW.fecha IS DISTINCT FROM OLD.fecha
     OR NEW.referencia IS DISTINCT FROM OLD.referencia THEN
    RAISE EXCEPTION 'Un pago registrado no se modifica: anúlalo y registra uno nuevo.';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS pagos_proteger_trg ON public.pagos;
CREATE TRIGGER pagos_proteger_trg BEFORE UPDATE OR DELETE ON public.pagos
  FOR EACH ROW EXECUTE FUNCTION public.pagos_proteger();

CREATE OR REPLACE FUNCTION public.pago_detalle_proteger()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'El detalle de un pago no se modifica ni se elimina.';
END;
$$;

DROP TRIGGER IF EXISTS pago_detalle_proteger_trg ON public.pago_detalle;
CREATE TRIGGER pago_detalle_proteger_trg BEFORE UPDATE OR DELETE ON public.pago_detalle
  FOR EACH ROW EXECUTE FUNCTION public.pago_detalle_proteger();

CREATE OR REPLACE FUNCTION public.registrar_pago(
  p_paciente   uuid,
  p_monto      integer,
  p_metodo     text,
  p_detalle    jsonb,
  p_usuario    uuid,
  p_referencia text DEFAULT NULL,
  p_boleta     text DEFAULT NULL,
  p_nota       text DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE
  v_id uuid;
  v_numero bigint;
  v_suma integer;
  v_item public.presupuesto_items%ROWTYPE;
  v_nombre text;
  v_trat_estado text;
  r record;
BEGIN
  IF p_monto IS NULL OR p_monto <= 0 THEN RAISE EXCEPTION 'El monto debe ser mayor a cero.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.pacientes WHERE id = p_paciente) THEN
    RAISE EXCEPTION 'Paciente no encontrado.';
  END IF;
  IF p_detalle IS NULL OR jsonb_typeof(p_detalle) <> 'array' OR jsonb_array_length(p_detalle) = 0 THEN
    RAISE EXCEPTION 'Indica a qué prestaciones se aplica el pago.';
  END IF;

  SELECT COALESCE(sum((e ->> 'monto')::integer), 0) INTO v_suma FROM jsonb_array_elements(p_detalle) e;
  IF v_suma <> p_monto THEN
    RAISE EXCEPTION '%', 'La distribución ($' || v_suma || ') no coincide con el monto del pago ($' || p_monto || ').';
  END IF;

  INSERT INTO public.pagos (paciente_id, monto, metodo, referencia, numero_boleta, nota, registrado_por)
  VALUES (p_paciente, p_monto, p_metodo, NULLIF(trim(p_referencia), ''), NULLIF(trim(p_boleta), ''),
          NULLIF(trim(p_nota), ''), p_usuario)
  RETURNING id, numero INTO v_id, v_numero;

  FOR r IN
    SELECT (e ->> 'item_id')::uuid AS item_id, (e ->> 'monto')::integer AS monto
      FROM jsonb_array_elements(p_detalle) e
  LOOP
    IF r.monto IS NULL OR r.monto <= 0 THEN
      RAISE EXCEPTION 'Cada monto aplicado debe ser mayor a cero.';
    END IF;

    SELECT * INTO v_item FROM public.presupuesto_items WHERE id = r.item_id FOR UPDATE;
    IF NOT FOUND OR v_item.paciente_id <> p_paciente THEN
      RAISE EXCEPTION 'Una de las prestaciones no pertenece al paciente.';
    END IF;

    v_nombre := (SELECT nombre FROM public.prestaciones WHERE id = v_item.prestacion_id);
    v_trat_estado := (SELECT estado FROM public.presupuestos WHERE id = v_item.presupuesto_id);
    IF v_item.estado = 'ANULADO' OR v_trat_estado = 'ANULADO' THEN
      RAISE EXCEPTION '%', 'No se puede pagar "' || v_nombre || '": está anulada.';
    END IF;

    IF r.monto > v_item.precio - v_item.abonado THEN
      RAISE EXCEPTION '%', 'El abono a "' || v_nombre || '" supera su saldo ($' || (v_item.precio - v_item.abonado) || ').';
    END IF;

    INSERT INTO public.pago_detalle (pago_id, item_id, monto) VALUES (v_id, r.item_id, r.monto);
    UPDATE public.presupuesto_items SET abonado = abonado + r.monto WHERE id = r.item_id;
  END LOOP;

  PERFORM public.registrar_evento(p_paciente, 'PAGO', 'CREADO',
    'Pago N° ' || v_numero || ' · $' || to_char(p_monto, 'FM999G999G999'),
    CASE p_metodo WHEN 'EFECTIVO' THEN 'Efectivo' WHEN 'DEBITO' THEN 'Débito' WHEN 'CREDITO' THEN 'Crédito' ELSE 'Transferencia' END
      || COALESCE(' · Ref. ' || NULLIF(trim(p_referencia), ''), '')
      || COALESCE(' · Boleta ' || NULLIF(trim(p_boleta), ''), ''),
    NULL, 'pagos', v_id, NULL, p_usuario);

  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.anular_pago(p_pago uuid, p_usuario uuid, p_motivo text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  v_pago public.pagos%ROWTYPE;
  d record;
BEGIN
  IF length(trim(COALESCE(p_motivo, ''))) < 3 THEN RAISE EXCEPTION 'Indica el motivo de la anulación.'; END IF;

  SELECT * INTO v_pago FROM public.pagos WHERE id = p_pago FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Pago no encontrado.'; END IF;
  IF v_pago.estado <> 'VIGENTE' THEN RAISE EXCEPTION 'El pago ya está anulado.'; END IF;

  FOR d IN SELECT item_id, monto FROM public.pago_detalle WHERE pago_id = p_pago LOOP
    UPDATE public.presupuesto_items SET abonado = abonado - d.monto WHERE id = d.item_id;
  END LOOP;

  UPDATE public.pagos
     SET estado = 'ANULADO', anulado_por = p_usuario, fecha_anulacion = now(), motivo_anulacion = trim(p_motivo)
   WHERE id = p_pago;

  PERFORM public.registrar_evento(v_pago.paciente_id, 'PAGO', 'ANULADO',
    'Pago N° ' || v_pago.numero || ' anulado · $' || to_char(v_pago.monto, 'FM999G999G999'),
    trim(p_motivo), NULL, 'pagos', p_pago, NULL, p_usuario);
END;
$$;

CREATE OR REPLACE FUNCTION public.anular_tratamiento(p_presupuesto uuid, p_usuario uuid, p_motivo text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  v_pres public.presupuestos%ROWTYPE;
BEGIN
  IF length(trim(COALESCE(p_motivo, ''))) = 0 THEN RAISE EXCEPTION 'Indica el motivo de la anulación.'; END IF;

  SELECT * INTO v_pres FROM public.presupuestos WHERE id = p_presupuesto FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Tratamiento no encontrado.'; END IF;
  IF v_pres.estado <> 'ACTIVO' THEN RAISE EXCEPTION 'El tratamiento ya está finalizado o anulado.'; END IF;
  IF EXISTS (SELECT 1 FROM public.presupuesto_items WHERE presupuesto_id = p_presupuesto AND progreso > 0) THEN
    RAISE EXCEPTION 'No se puede anular: tiene prestaciones con avances (ya hay montos habilitados para cobro).';
  END IF;
  IF EXISTS (SELECT 1 FROM public.presupuesto_items WHERE presupuesto_id = p_presupuesto AND abonado > 0) THEN
    RAISE EXCEPTION 'No se puede anular: tiene abonos registrados. Anula primero esos pagos.';
  END IF;

  UPDATE public.presupuesto_items
     SET estado = 'ANULADO', motivo_anulacion = 'Tratamiento anulado: ' || trim(p_motivo)
   WHERE presupuesto_id = p_presupuesto AND estado <> 'ANULADO';

  UPDATE public.presupuestos SET estado = 'ANULADO', motivo_anulacion = trim(p_motivo) WHERE id = p_presupuesto;

  PERFORM public.registrar_evento(v_pres.paciente_id, 'PRESUPUESTO', 'ANULADO',
    'Tratamiento N° ' || v_pres.numero || ' anulado: ' || v_pres.nombre, trim(p_motivo),
    NULL, 'presupuestos', p_presupuesto, NULL, p_usuario);
END;
$$;

CREATE OR REPLACE FUNCTION public.items_anular_con_abonos()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.estado = 'ANULADO' AND OLD.estado <> 'ANULADO' AND OLD.abonado > 0 THEN
    RAISE EXCEPTION 'No se puede anular una prestación con abonos. Anula primero el pago.';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS items_anular_con_abonos_trg ON public.presupuesto_items;
CREATE TRIGGER items_anular_con_abonos_trg BEFORE UPDATE ON public.presupuesto_items
  FOR EACH ROW EXECUTE FUNCTION public.items_anular_con_abonos();

