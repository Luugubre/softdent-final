CREATE OR REPLACE FUNCTION public.registro_solo_insercion()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Este registro no se modifica ni se elimina.';
END;
$$;

-- ---------- Accesos a fichas ----------
CREATE TABLE IF NOT EXISTS public.accesos_ficha (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id uuid NOT NULL REFERENCES public.pacientes(id) ON DELETE RESTRICT,
  usuario_id  uuid NOT NULL REFERENCES public.perfiles(id) ON DELETE RESTRICT,
  seccion     text NOT NULL,
  ip          text,
  fecha       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS accesos_ficha_fecha_idx    ON public.accesos_ficha (fecha DESC);
CREATE INDEX IF NOT EXISTS accesos_ficha_paciente_idx ON public.accesos_ficha (paciente_id, fecha DESC);
CREATE INDEX IF NOT EXISTS accesos_ficha_usuario_idx  ON public.accesos_ficha (usuario_id, fecha DESC);

DROP TRIGGER IF EXISTS accesos_ficha_solo_insercion ON public.accesos_ficha;
CREATE TRIGGER accesos_ficha_solo_insercion BEFORE UPDATE OR DELETE ON public.accesos_ficha
  FOR EACH ROW EXECUTE FUNCTION public.registro_solo_insercion();

-- Un acceso por usuario, ficha y sección cada 10 minutos
CREATE OR REPLACE FUNCTION public.registrar_acceso_ficha(p_usuario uuid, p_paciente uuid, p_seccion text, p_ip text)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('acceso:' || p_usuario || ':' || p_paciente));
  IF EXISTS (
    SELECT 1 FROM public.accesos_ficha
     WHERE usuario_id = p_usuario AND paciente_id = p_paciente AND seccion = p_seccion
       AND fecha > now() - interval '10 minutes'
  ) THEN
    RETURN;
  END IF;
  INSERT INTO public.accesos_ficha (paciente_id, usuario_id, seccion, ip)
  VALUES (p_paciente, p_usuario, left(p_seccion, 60), left(p_ip, 64));
END;
$$;

-- ---------- Documentos clínicos ----------
CREATE TABLE IF NOT EXISTS public.documentos_clinicos (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  folio            bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  paciente_id      uuid NOT NULL REFERENCES public.pacientes(id) ON DELETE RESTRICT,
  profesional_id   uuid NOT NULL REFERENCES public.perfiles(id) ON DELETE RESTRICT,
  tipo             text NOT NULL,
  titulo           text NOT NULL,
  contenido        text NOT NULL,
  destinatario     text,
  plantilla_id     uuid REFERENCES public.plantillas_documento(id) ON DELETE SET NULL,
  estado           text NOT NULL DEFAULT 'EMITIDO',
  motivo_anulacion text,
  anulado_at       timestamptz,
  anulado_por      uuid REFERENCES public.perfiles(id) ON DELETE SET NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT documentos_clinicos_tipo_chk   CHECK (tipo IN ('CERTIFICADO', 'INDICACIONES', 'DERIVACION', 'DOCUMENTO')),
  CONSTRAINT documentos_clinicos_estado_chk CHECK (estado IN ('EMITIDO', 'ANULADO'))
);
CREATE INDEX IF NOT EXISTS documentos_clinicos_paciente_idx ON public.documentos_clinicos (paciente_id, created_at DESC);

-- Emitido no se modifica: solo se puede anular
CREATE OR REPLACE FUNCTION public.documento_inmutable()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Los documentos clínicos no se eliminan: se anulan.';
  END IF;
  IF (to_jsonb(NEW) - ARRAY['estado', 'motivo_anulacion', 'anulado_at', 'anulado_por'])
     IS DISTINCT FROM (to_jsonb(OLD) - ARRAY['estado', 'motivo_anulacion', 'anulado_at', 'anulado_por']) THEN
    RAISE EXCEPTION 'Un documento emitido no se modifica: anúlalo y emite uno nuevo.';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS documentos_clinicos_inmutable ON public.documentos_clinicos;
CREATE TRIGGER documentos_clinicos_inmutable BEFORE UPDATE OR DELETE ON public.documentos_clinicos
  FOR EACH ROW EXECUTE FUNCTION public.documento_inmutable();

CREATE OR REPLACE FUNCTION public.emitir_documento(
  p_usuario uuid, p_paciente uuid, p_tipo text, p_titulo text, p_contenido text,
  p_destinatario text DEFAULT NULL, p_plantilla uuid DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE
  v_id    uuid;
  v_folio bigint;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.perfiles WHERE id = p_usuario AND activo AND rol IN ('ADMINISTRADOR', 'DENTISTA')) THEN
    RAISE EXCEPTION 'Solo un profesional activo puede emitir documentos clínicos.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.pacientes WHERE id = p_paciente) THEN
    RAISE EXCEPTION 'El paciente no existe.';
  END IF;
  IF length(trim(COALESCE(p_titulo, ''))) < 3 OR length(trim(COALESCE(p_contenido, ''))) < 10 THEN
    RAISE EXCEPTION 'Completa el título y el contenido del documento.';
  END IF;

  INSERT INTO public.documentos_clinicos (paciente_id, profesional_id, tipo, titulo, contenido, destinatario, plantilla_id)
  VALUES (p_paciente, p_usuario, p_tipo, trim(p_titulo), p_contenido, NULLIF(trim(p_destinatario), ''), p_plantilla)
  RETURNING id, folio INTO v_id, v_folio;

  PERFORM public.registrar_evento(p_paciente, 'DOCUMENTO', 'CREADO', trim(p_titulo) || ' · folio ' || v_folio,
    NULLIF(trim(p_destinatario), ''), NULL, 'documentos_clinicos', v_id, jsonb_build_object('tipo', p_tipo), p_usuario);
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.anular_documento(p_documento uuid, p_usuario uuid, p_motivo text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  v_doc public.documentos_clinicos;
  v_rol text;
BEGIN
  IF length(trim(COALESCE(p_motivo, ''))) < 5 THEN
    RAISE EXCEPTION 'Indica el motivo de la anulación (mínimo 5 caracteres).';
  END IF;
  SELECT * INTO v_doc FROM public.documentos_clinicos WHERE id = p_documento FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'El documento no existe.'; END IF;
  IF v_doc.estado <> 'EMITIDO' THEN RAISE EXCEPTION 'El documento ya está anulado.'; END IF;

  SELECT rol INTO v_rol FROM public.perfiles WHERE id = p_usuario;
  IF v_rol IS DISTINCT FROM 'ADMINISTRADOR' AND v_doc.profesional_id <> p_usuario THEN
    RAISE EXCEPTION 'Solo puedes anular tus propios documentos.';
  END IF;

  UPDATE public.documentos_clinicos
     SET estado = 'ANULADO', motivo_anulacion = left(trim(p_motivo), 300), anulado_at = now(), anulado_por = p_usuario
   WHERE id = p_documento;

  PERFORM public.registrar_evento(v_doc.paciente_id, 'DOCUMENTO', 'ANULADO', v_doc.titulo || ' · folio ' || v_doc.folio,
    trim(p_motivo), NULL, 'documentos_clinicos', p_documento, NULL, p_usuario);
END;
$$;

-- ---------- Reporte de desempeño por profesional ----------
CREATE OR REPLACE FUNCTION public.reporte_desempeno(p_desde date, p_hasta date)
RETURNS TABLE (
  profesional_id         uuid,
  profesional_nombre     text,
  citas_total            integer,
  realizadas             integer,
  no_asistio             integer,
  canceladas             integer,
  pacientes_atendidos    integer,
  minutos_agendados      integer,
  minutos_disponibles    integer,
  produccion             bigint,
  presupuestos_creados   integer,
  presupuestos_aprobados integer,
  recetas                integer,
  documentos             integer
) LANGUAGE sql STABLE AS $$
  SELECT
    pr.id,
    pr.nombre_completo,
    COALESCE(c.total, 0)::int,
    COALESCE(c.realizadas, 0)::int,
    COALESCE(c.no_asistio, 0)::int,
    COALESCE(c.canceladas, 0)::int,
    COALESCE(c.pacientes, 0)::int,
    COALESCE(c.minutos, 0)::int,
    COALESCE((
      SELECT sum(extract(epoch FROM t.hora_fin - t.hora_inicio) / 60)
        FROM generate_series(p_desde, p_hasta, interval '1 day') d,
             public.tramos_atencion(pr.id, d::date) t
    ), 0)::int,
    COALESCE((
      SELECT sum(a.monto) FROM public.item_avances a
       WHERE a.profesional_id = pr.id AND a.monto > 0
         AND (a.created_at AT TIME ZONE 'America/Santiago')::date BETWEEN p_desde AND p_hasta
    ), 0)::bigint,
    (SELECT count(*) FROM public.presupuestos ps
      WHERE ps.profesional_id = pr.id AND ps.estado <> 'ANULADO'
        AND (ps.created_at AT TIME ZONE 'America/Santiago')::date BETWEEN p_desde AND p_hasta)::int,
    (SELECT count(*) FROM public.presupuestos ps
      WHERE ps.profesional_id = pr.id AND ps.aprobacion = 'APROBADO'
        AND (ps.created_at AT TIME ZONE 'America/Santiago')::date BETWEEN p_desde AND p_hasta)::int,
    (SELECT count(*) FROM public.recetas r
      WHERE r.profesional_id = pr.id AND r.estado = 'EMITIDA'
        AND (r.created_at AT TIME ZONE 'America/Santiago')::date BETWEEN p_desde AND p_hasta)::int,
    (SELECT count(*) FROM public.documentos_clinicos dc
      WHERE dc.profesional_id = pr.id AND dc.estado = 'EMITIDO'
        AND (dc.created_at AT TIME ZONE 'America/Santiago')::date BETWEEN p_desde AND p_hasta)::int
  FROM public.perfiles pr
  LEFT JOIN LATERAL (
    SELECT count(*) FILTER (WHERE ci.estado <> 'REAGENDADA')                        AS total,
           count(*) FILTER (WHERE ci.estado = 'REALIZADA')                          AS realizadas,
           count(*) FILTER (WHERE ci.estado = 'NO_ASISTIO')                         AS no_asistio,
           count(*) FILTER (WHERE ci.estado = 'CANCELADA')                          AS canceladas,
           count(DISTINCT ci.paciente_id) FILTER (WHERE ci.estado = 'REALIZADA')    AS pacientes,
           sum(ci.duracion_min) FILTER (WHERE ci.estado NOT IN ('CANCELADA', 'REAGENDADA')) AS minutos
      FROM public.citas ci
     WHERE ci.profesional_id = pr.id
       AND (ci.inicio AT TIME ZONE 'America/Santiago')::date BETWEEN p_desde AND p_hasta
  ) c ON true
  WHERE pr.rol = 'DENTISTA' AND (pr.activo OR COALESCE(c.total, 0) > 0)
  ORDER BY pr.nombre_completo;
$$;

-- ---------- Próximas horas: filtro por prestación ----------
DROP FUNCTION IF EXISTS public.proximas_horas(integer, date, uuid, text, integer);
CREATE OR REPLACE FUNCTION public.proximas_horas(
  p_duracion    integer,
  p_desde       date,
  p_profesional uuid DEFAULT NULL,
  p_turno       text DEFAULT 'cualquiera',
  p_limite      integer DEFAULT 10,
  p_prestacion  uuid DEFAULT NULL
) RETURNS TABLE (fecha date, hora text, profesional_id uuid, profesional_nombre text)
LANGUAGE plpgsql STABLE AS $$
DECLARE
  d date;
  pr record;
  h record;
  v_total integer := 0;
  v_por_dia integer;
  v_ultimo_fin integer;
  v_min integer;
  v_restringida boolean := p_prestacion IS NOT NULL
    AND EXISTS (SELECT 1 FROM public.prestacion_profesionales WHERE prestacion_id = p_prestacion);
BEGIN
  FOR i IN 0..120 LOOP
    d := GREATEST(p_desde, public.hoy_chile()) + i;
    FOR pr IN
      SELECT p.id, p.nombre_completo FROM public.perfiles p
       WHERE p.activo AND p.rol = 'DENTISTA' AND (p_profesional IS NULL OR p.id = p_profesional)
         AND (NOT v_restringida OR EXISTS (
               SELECT 1 FROM public.prestacion_profesionales pp
                WHERE pp.prestacion_id = p_prestacion AND pp.profesional_id = p.id))
       ORDER BY p.nombre_completo
    LOOP
      v_por_dia := 0;
      v_ultimo_fin := -1;
      FOR h IN SELECT x.hora FROM public.horas_disponibles(pr.id, d, p_duracion) x LOOP
        v_min := split_part(h.hora, ':', 1)::int * 60 + split_part(h.hora, ':', 2)::int;
        CONTINUE WHEN p_turno = 'manana' AND v_min >= 780;
        CONTINUE WHEN p_turno = 'tarde' AND v_min < 780;
        CONTINUE WHEN v_min < v_ultimo_fin;
        fecha := d; hora := h.hora; profesional_id := pr.id; profesional_nombre := pr.nombre_completo;
        RETURN NEXT;
        v_total := v_total + 1;
        v_por_dia := v_por_dia + 1;
        v_ultimo_fin := v_min + p_duracion;
        EXIT WHEN v_por_dia >= 3;
      END LOOP;
    END LOOP;
    EXIT WHEN v_total >= p_limite;
  END LOOP;
END;
$$;

