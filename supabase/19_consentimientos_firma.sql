-- =====================================================================
-- 19 · Consentimientos informados con firma online
-- Idempotente.
-- =====================================================================

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'estado_consentimiento') THEN
    CREATE TYPE public.estado_consentimiento AS ENUM ('BORRADOR', 'PENDIENTE_FIRMA', 'FIRMADO', 'REVOCADO');
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.plantillas_consentimiento (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  titulo             text NOT NULL,
  contenido_template text NOT NULL,
  activa             boolean DEFAULT true,
  created_at         timestamptz DEFAULT now(),
  updated_at         timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.consentimientos_paciente (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  folio                 integer GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  paciente_id           uuid NOT NULL REFERENCES public.pacientes(id) ON DELETE RESTRICT,
  cita_id               uuid REFERENCES public.citas(id) ON DELETE SET NULL,
  doctor_id             uuid REFERENCES public.perfiles(id) ON DELETE SET NULL,
  plantilla_id          uuid REFERENCES public.plantillas_consentimiento(id) ON DELETE SET NULL,
  estado                public.estado_consentimiento NOT NULL DEFAULT 'BORRADOR',
  titulo                text NOT NULL,
  contenido_snapshot    text,
  hash_contenido_sha256 text,
  firma_paciente_url    text,
  firma_doctor_url      text,
  firmado_at            timestamptz,
  firmante_nombre       text,
  firmante_rut          text,
  firmante_es_apoderado boolean DEFAULT false,
  firmante_ip           text,
  firmante_user_agent   text,
  pdf_base64            text,
  created_at            timestamptz DEFAULT now(),
  updated_at            timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.tokens_firma_consentimiento (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  consentimiento_id uuid NOT NULL REFERENCES public.consentimientos_paciente(id) ON DELETE CASCADE,
  token_hash        text NOT NULL,
  intentos_fallidos integer NOT NULL DEFAULT 0,
  max_intentos      integer NOT NULL DEFAULT 5,
  expires_at        timestamptz NOT NULL,
  usado_at          timestamptz,
  created_at        timestamptz DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS tokens_firma_hash_key ON public.tokens_firma_consentimiento (token_hash);
CREATE INDEX IF NOT EXISTS consentimientos_paciente_idx ON public.consentimientos_paciente (paciente_id, created_at DESC);
CREATE INDEX IF NOT EXISTS consentimientos_cita_idx ON public.consentimientos_paciente (cita_id);

-- RLS activo sin políticas: acceso solo desde el servidor (service role).
ALTER TABLE public.plantillas_consentimiento   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.consentimientos_paciente    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tokens_firma_consentimiento ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.plantillas_consentimiento, public.consentimientos_paciente, public.tokens_firma_consentimiento
  FROM anon, authenticated;
