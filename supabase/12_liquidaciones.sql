-- =====================================================================
-- Liquidaciones de profesionales
-- Pegar en Supabase → SQL Editor → Run (después de 01 a 11)
--
-- Regla: a cada profesional se le paga su % sobre lo que ÉL evolucionó,
-- solo cuando la prestación está evolucionada al 100% Y pagada al 100%.
-- Si una prestación la avanzaron dos dentistas (ej. 50% cada uno),
-- a cada uno le corresponde el tramo que hizo.
-- =====================================================================

-- Tabla antigua del SQL de Prisma (tenía dentista_id)
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
              WHERE table_schema = 'public' AND table_name = 'liquidaciones' AND column_name = 'dentista_id') THEN
    DROP TABLE public.liquidaciones CASCADE;
  END IF;
END;
$$;


-- =====================================================================
-- 1. % DE LIQUIDACIÓN DE CADA PROFESIONAL
-- =====================================================================
ALTER TABLE public.perfiles ADD COLUMN IF NOT EXISTS porcentaje_liquidacion numeric(5,2);
ALTER TABLE public.perfiles DROP CONSTRAINT IF EXISTS perfiles_porcentaje_chk;
ALTER TABLE public.perfiles ADD CONSTRAINT perfiles_porcentaje_chk
  CHECK (porcentaje_liquidacion IS NULL OR porcentaje_liquidacion BETWEEN 0 AND 100);


-- =====================================================================
-- 2. LIQUIDACIONES
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.liquidaciones (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  numero           bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  profesional_id   uuid NOT NULL REFERENCES public.perfiles(id) ON DELETE RESTRICT,
  fecha_corte      date NOT NULL,                     -- incluye lo liquidable hasta esta fecha
  porcentaje       numeric(5,2) NOT NULL,             -- % vigente al generar
  cantidad         integer NOT NULL DEFAULT 0,
  total_base       integer NOT NULL DEFAULT 0,        -- valor de lo realizado
  total            integer NOT NULL DEFAULT 0,        -- a pagar al profesional
  nota             text,
  estado           text NOT NULL DEFAULT 'EMITIDA',
  creado_por       uuid REFERENCES public.perfiles(id) ON DELETE SET NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  pagado_por       uuid REFERENCES public.perfiles(id) ON DELETE SET NULL,
  fecha_pago       timestamptz,
  metodo_pago      text,
  referencia_pago  text,
  anulado_por      uuid REFERENCES public.perfiles(id) ON DELETE SET NULL,
  fecha_anulacion  timestamptz,
  motivo_anulacion text,

  CONSTRAINT liquidaciones_estado_chk CHECK (estado IN ('EMITIDA', 'PAGADA', 'ANULADA')),
  CONSTRAINT liquidaciones_metodo_chk CHECK (metodo_pago IS NULL OR metodo_pago IN ('TRANSFERENCIA', 'EFECTIVO', 'CHEQUE'))
);

CREATE INDEX IF NOT EXISTS liquidaciones_profesional_idx ON public.liquidaciones (profesional_id, created_at DESC);

-- Cada tramo (avance) liquidado; se guarda una "foto" de los datos
CREATE TABLE IF NOT EXISTS public.liquidacion_detalle (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  liquidacion_id    uuid NOT NULL REFERENCES public.liquidaciones(id) ON DELETE RESTRICT,
  avance_id         uuid NOT NULL REFERENCES public.item_avances(id) ON DELETE RESTRICT,
  item_id           uuid NOT NULL REFERENCES public.presupuesto_items(id) ON DELETE RESTRICT,
  paciente_id       uuid NOT NULL REFERENCES public.pacientes(id) ON DELETE RESTRICT,
  paciente_nombre   text NOT NULL,
  prestacion_nombre text NOT NULL,
  pieza             integer,
  tramo             text NOT NULL,                    -- "0% → 100%"
  fecha_realizado   timestamptz,
  fecha_pagado      timestamptz,
  monto_base        integer NOT NULL,
  porcentaje        numeric(5,2) NOT NULL,
  monto             integer NOT NULL,
  vigente           boolean NOT NULL DEFAULT true     -- false si la liquidación se anula
);

-- Un mismo tramo no se puede liquidar dos veces
CREATE UNIQUE INDEX IF NOT EXISTS liquidacion_detalle_avance_unico
  ON public.liquidacion_detalle (avance_id) WHERE vigente;
CREATE INDEX IF NOT EXISTS liquidacion_detalle_item_idx ON public.liquidacion_detalle (item_id) WHERE vigente;
CREATE INDEX IF NOT EXISTS liquidacion_detalle_liq_idx ON public.liquidacion_detalle (liquidacion_id);

ALTER TABLE public.liquidaciones       ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.liquidacion_detalle ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.liquidaciones_no_borrar()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Las liquidaciones no se eliminan: se anulan.';
END;
$$;

DROP TRIGGER IF EXISTS liquidaciones_no_borrar_trg ON public.liquidaciones;
CREATE TRIGGER liquidaciones_no_borrar_trg BEFORE DELETE ON public.liquidaciones
  FOR EACH ROW EXECUTE FUNCTION public.liquidaciones_no_borrar();

DROP TRIGGER IF EXISTS liquidacion_detalle_no_borrar_trg ON public.liquidacion_detalle;
CREATE TRIGGER liquidacion_detalle_no_borrar_trg BEFORE DELETE ON public.liquidacion_detalle
  FOR EACH ROW EXECUTE FUNCTION public.liquidaciones_no_borrar();


-- =====================================================================
-- 3. VISTA: producción de cada profesional (tramo por tramo)
-- =====================================================================
DROP VIEW IF EXISTS public.v_produccion_profesional;
CREATE VIEW public.v_produccion_profesional WITH (security_invoker = true) AS
SELECT
  a.id                          AS avance_id,
  a.item_id,
  a.profesional_id,
  pf.nombre_completo            AS profesional_nombre,
  pf.porcentaje_liquidacion     AS porcentaje,
  i.paciente_id,
  pa.nombres || ' ' || pa.apellidos AS paciente_nombre,
  pa.numero_ficha,
  pr.nombre                     AS prestacion_nombre,
  i.pieza,
  ps.numero                     AS tratamiento_numero,
  a.progreso_anterior,
  a.progreso_nuevo,
  a.monto                       AS monto_base,
  a.created_at                  AS fecha_avance,
  i.precio,
  i.progreso,
  i.abonado,
  i.completado_en,
  pg.fecha_pagado,
  (i.progreso = 100 AND i.abonado = i.precio)             AS liquidable,
  CASE WHEN i.progreso = 100 AND i.abonado = i.precio
       THEN greatest(i.completado_en, pg.fecha_pagado) END AS fecha_liquidable,
  ld.liquidacion_id,
  l.numero                      AS liquidacion_numero
FROM public.item_avances a
JOIN public.presupuesto_items i ON i.id = a.item_id
JOIN public.presupuestos ps     ON ps.id = i.presupuesto_id
JOIN public.pacientes pa        ON pa.id = i.paciente_id
JOIN public.prestaciones pr     ON pr.id = i.prestacion_id
JOIN public.perfiles pf         ON pf.id = a.profesional_id
LEFT JOIN LATERAL (
  SELECT max(p.fecha) AS fecha_pagado
    FROM public.pago_detalle d JOIN public.pagos p ON p.id = d.pago_id
   WHERE d.item_id = i.id AND p.estado = 'VIGENTE'
) pg ON true
LEFT JOIN public.liquidacion_detalle ld ON ld.avance_id = a.id AND ld.vigente
LEFT JOIN public.liquidaciones l        ON l.id = ld.liquidacion_id
WHERE a.monto > 0 AND i.estado <> 'ANULADO';


-- =====================================================================
-- 4. GENERAR LIQUIDACIÓN (toma todo lo liquidable pendiente hasta la fecha de corte)
-- =====================================================================
CREATE OR REPLACE FUNCTION public.generar_liquidacion(
  p_profesional uuid,
  p_fecha_corte date,
  p_usuario     uuid,
  p_nota        text DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE
  v_pct numeric(5,2);
  v_id uuid;
  v_cantidad integer;
BEGIN
  SELECT porcentaje_liquidacion INTO v_pct FROM public.perfiles WHERE id = p_profesional FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Profesional no encontrado.'; END IF;
  IF v_pct IS NULL THEN RAISE EXCEPTION 'El profesional no tiene configurado su porcentaje de liquidación.'; END IF;
  IF p_fecha_corte IS NULL OR p_fecha_corte > public.hoy_chile() THEN
    RAISE EXCEPTION 'La fecha de corte no puede ser futura.';
  END IF;

  INSERT INTO public.liquidaciones (profesional_id, fecha_corte, porcentaje, nota, creado_por)
  VALUES (p_profesional, p_fecha_corte, v_pct, NULLIF(trim(p_nota), ''), p_usuario)
  RETURNING id INTO v_id;

  INSERT INTO public.liquidacion_detalle
    (liquidacion_id, avance_id, item_id, paciente_id, paciente_nombre, prestacion_nombre, pieza, tramo,
     fecha_realizado, fecha_pagado, monto_base, porcentaje, monto)
  SELECT v_id, v.avance_id, v.item_id, v.paciente_id, v.paciente_nombre, v.prestacion_nombre, v.pieza,
         v.progreso_anterior || '% → ' || v.progreso_nuevo || '%',
         v.completado_en, v.fecha_pagado, v.monto_base, v_pct, round(v.monto_base * v_pct / 100.0)::int
    FROM public.v_produccion_profesional v
   WHERE v.profesional_id = p_profesional
     AND v.liquidable
     AND v.liquidacion_id IS NULL
     AND (v.fecha_liquidable AT TIME ZONE 'America/Santiago')::date <= p_fecha_corte;

  GET DIAGNOSTICS v_cantidad = ROW_COUNT;
  IF v_cantidad = 0 THEN
    RAISE EXCEPTION 'No hay prestaciones terminadas y pagadas pendientes de liquidar hasta esa fecha.';
  END IF;

  UPDATE public.liquidaciones l
     SET cantidad = v_cantidad,
         total_base = (SELECT sum(monto_base) FROM public.liquidacion_detalle WHERE liquidacion_id = v_id),
         total      = (SELECT sum(monto)      FROM public.liquidacion_detalle WHERE liquidacion_id = v_id)
   WHERE l.id = v_id;

  RETURN v_id;
END;
$$;


-- =====================================================================
-- 5. MARCAR COMO PAGADA / ANULAR
-- =====================================================================
CREATE OR REPLACE FUNCTION public.pagar_liquidacion(p_liquidacion uuid, p_usuario uuid, p_metodo text, p_referencia text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  v_estado text;
BEGIN
  SELECT estado INTO v_estado FROM public.liquidaciones WHERE id = p_liquidacion FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Liquidación no encontrada.'; END IF;
  IF v_estado <> 'EMITIDA' THEN RAISE EXCEPTION 'Solo se puede pagar una liquidación emitida.'; END IF;
  IF p_metodo NOT IN ('TRANSFERENCIA', 'EFECTIVO', 'CHEQUE') THEN RAISE EXCEPTION 'Método de pago no válido.'; END IF;
  IF p_metodo <> 'EFECTIVO' AND length(trim(COALESCE(p_referencia, ''))) = 0 THEN
    RAISE EXCEPTION 'Ingresa el N° de operación o de cheque.';
  END IF;

  UPDATE public.liquidaciones
     SET estado = 'PAGADA', pagado_por = p_usuario, fecha_pago = now(),
         metodo_pago = p_metodo, referencia_pago = NULLIF(trim(p_referencia), '')
   WHERE id = p_liquidacion;
END;
$$;

CREATE OR REPLACE FUNCTION public.anular_liquidacion(p_liquidacion uuid, p_usuario uuid, p_motivo text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  v_estado text;
BEGIN
  IF length(trim(COALESCE(p_motivo, ''))) < 3 THEN RAISE EXCEPTION 'Indica el motivo de la anulación.'; END IF;

  SELECT estado INTO v_estado FROM public.liquidaciones WHERE id = p_liquidacion FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Liquidación no encontrada.'; END IF;
  IF v_estado = 'PAGADA' THEN RAISE EXCEPTION 'Una liquidación ya pagada no se puede anular.'; END IF;
  IF v_estado = 'ANULADA' THEN RAISE EXCEPTION 'La liquidación ya está anulada.'; END IF;

  -- Las prestaciones vuelven a quedar pendientes de liquidar
  UPDATE public.liquidacion_detalle SET vigente = false WHERE liquidacion_id = p_liquidacion;

  UPDATE public.liquidaciones
     SET estado = 'ANULADA', anulado_por = p_usuario, fecha_anulacion = now(), motivo_anulacion = trim(p_motivo)
   WHERE id = p_liquidacion;
END;
$$;

-- El detalle solo puede pasar de vigente a no vigente (al anular)
CREATE OR REPLACE FUNCTION public.liquidacion_detalle_proteger()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.vigente = false AND OLD.vigente = true
     AND (NEW.monto, NEW.monto_base, NEW.avance_id, NEW.liquidacion_id) = (OLD.monto, OLD.monto_base, OLD.avance_id, OLD.liquidacion_id) THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION 'El detalle de una liquidación no se modifica.';
END;
$$;

DROP TRIGGER IF EXISTS liquidacion_detalle_proteger_trg ON public.liquidacion_detalle;
CREATE TRIGGER liquidacion_detalle_proteger_trg BEFORE UPDATE ON public.liquidacion_detalle
  FOR EACH ROW EXECUTE FUNCTION public.liquidacion_detalle_proteger();


-- =====================================================================
-- 6. Un pago que cubre prestaciones ya liquidadas no se puede anular
-- =====================================================================
CREATE OR REPLACE FUNCTION public.anular_pago(p_pago uuid, p_usuario uuid, p_motivo text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  v_pago public.pagos%ROWTYPE;
  v_liq bigint;
  d record;
BEGIN
  IF length(trim(COALESCE(p_motivo, ''))) < 3 THEN RAISE EXCEPTION 'Indica el motivo de la anulación.'; END IF;

  SELECT * INTO v_pago FROM public.pagos WHERE id = p_pago FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Pago no encontrado.'; END IF;
  IF v_pago.estado <> 'VIGENTE' THEN RAISE EXCEPTION 'El pago ya está anulado.'; END IF;

  SELECT l.numero INTO v_liq
    FROM public.pago_detalle pd
    JOIN public.liquidacion_detalle ld ON ld.item_id = pd.item_id AND ld.vigente
    JOIN public.liquidaciones l ON l.id = ld.liquidacion_id
   WHERE pd.pago_id = p_pago
   LIMIT 1;
  IF v_liq IS NOT NULL THEN
    RAISE EXCEPTION '%', 'No se puede anular: este pago cubre prestaciones ya liquidadas al profesional (liquidación N° '
      || v_liq || '). Si la liquidación aún no se paga, anúlala primero.';
  END IF;

  FOR d IN SELECT item_id, monto FROM public.pago_detalle WHERE pago_id = p_pago LOOP
    UPDATE public.presupuesto_items SET abonado = abonado - d.monto WHERE id = d.item_id;
  END LOOP;

  UPDATE public.pagos
     SET estado = 'ANULADO', anulado_por = p_usuario, fecha_anulacion = now(), motivo_anulacion = trim(p_motivo)
   WHERE id = p_pago;

  PERFORM public.registrar_evento(v_pago.paciente_id, 'PAGO', 'ANULADO',
    'Pago N° ' || v_pago.numero || ' anulado · $' || to_char(v_pago.monto, 'FM999G999G999'),
    trim(p_motivo), NULL, 'pagos', p_pago, NULL, p_usuario);
END;
$$;

