import sanitizeHtml from "sanitize-html"

// Formato permitido en plantillas y documentos (editor de texto enriquecido)
export function limpiarHtmlDocumento(html: string): string {
  return sanitizeHtml(html, {
    allowedTags: ["p", "br", "div", "span", "strong", "b", "em", "i", "u", "s", "h1", "h2", "h3", "h4", "ul", "ol", "li", "blockquote", "hr"],
    allowedAttributes: {
      p: ["style"],
      div: ["style"],
      span: ["style"],
      h1: ["style"],
      h2: ["style"],
      h3: ["style"],
      h4: ["style"],
    },
    allowedStyles: {
      "*": {
        "text-align": [/^(left|right|center|justify)$/],
        "font-weight": [/^(normal|bold|[1-9]00)$/],
        "font-style": [/^(normal|italic)$/],
        "text-decoration": [/^(none|underline|line-through)$/],
      },
    },
    disallowedTagsMode: "discard",
  })
}
